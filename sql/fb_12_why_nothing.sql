-- ไฟล์ 2b ไม่แสดงอะไรเลยสักแถว  ซึ่งแปลว่าตาราง fb_sent ว่างเปล่า
-- เพราะไฟล์ 2b อ่านจาก fb_sent เป็นตัวตั้ง ถ้ามีแถวต้องเห็นแถว
--
-- ตาราง fb_sent ว่างเป็นเรื่องผิดปกติ เพราะควรมีอย่างน้อยสองกลุ่มอยู่แล้ว
--   ของที่ไฟล์ 3a กับ 3c จดกันย้อนหลังไว้ตอนติดตั้ง
--   ของที่ไฟล์ 9 จดไว้เมื่อวาน คือประกาศที่เริ่มไปแล้ว
-- ถ้าไม่มีสักแถว แปลว่ามีอย่างอื่นผิดอยู่ ต้องรู้ให้ได้ก่อนวันจันทร์
--
-- ------------------------------------------------------------
-- ไฟล์นี้ตอบสามคำถาม
-- ------------------------------------------------------------
-- หนึ่ง  งานตามเวลาได้ทำงานจริงไหม และตอบอะไรกลับมา
-- สอง   ตาราง fb_sent มีอะไรอยู่บ้าง
-- สาม   สวิตช์เปิดอยู่จริงไหม
--
-- ตัวแก้ไขแสดงผลของคำสั่งสุดท้ายคำสั่งเดียว จึงรวมไว้ในคำสั่งเดียว
-- ช่อง คำตอบของงาน คือสิ่งที่ฟังก์ชันคืนกลับมา บอกได้เลยว่าทำไมไม่ส่ง
--   ปิดอยู่          แปลว่าตอนนั้นสวิตช์ยังไม่เปิด
--   sent เป็น 0      แปลว่าเปิดแล้ว แต่ไม่มีเรื่องเข้าเงื่อนไข
--   sent มากกว่า 0   แปลว่ายิงออกไปแล้ว ต้องไปดูที่เพจ

select
  j.jobname                                                          as ชื่องาน,
  to_char(d.start_time at time zone 'Asia/Bangkok', 'DD/MM HH24:MI') as เวลาที่ทำงาน,
  d.status                                                           as สถานะ,
  left(coalesce(d.return_message, ''), 200)                          as คำตอบของงาน,
  (select count(*) from fb_sent)                                     as แถวในสมุดกันซ้ำ,
  (select count(*) from fb_sent where kind = 'advisory')             as แถวของประกาศ,
  (select count(*) from fb_sent where kind = 'death')                as แถวของข่าวเสียชีวิต,
  (select val #>> array[]::text[] from bs_settings where key = 'fbEnabled') as สวิตช์
from cron.job_run_details d
join cron.job j on j.jobid = d.jobid
where j.jobname like 'fb-%'
order by d.start_time desc
limit 20;

