-- ============================================================
-- 1) โค้ดที่รันอยู่จริงของคำสั่งบันทึก
-- ============================================================
-- ส่งภาพผลข้อนี้มาให้ดู หรือถ้ายาวไป ให้คัดลอกข้อความในช่องผลลัพธ์มาวางแทน
select p.proname            as ชื่อฟังก์ชัน,
       pg_get_function_identity_arguments(p.oid) as พารามิเตอร์,
       p.prosrc             as โค้ดที่ทำงานอยู่
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
 where n.nspname = 'public' and p.proname = 'officer_save_accident';

-- ============================================================
-- 2) ชนิดของคอลัมน์ในตารางอุบัติเหตุ
-- ============================================================
-- ถ้าคอลัมน์ไหนเป็น json (ไม่ใช่ jsonb) จะเป็นเบาะแสสำคัญ
select column_name as คอลัมน์, data_type as ชนิด
  from information_schema.columns
 where table_schema = 'public' and table_name = 'accidents'
 order by ordinal_position;

-- ============================================================
-- 3) ลองเพิ่มแถวตรง ๆ โดยไม่ผ่านฟังก์ชัน
-- ============================================================
-- ถ้าข้อนี้พังด้วย แปลว่าปัญหาอยู่ที่ตัวตาราง ไม่ใช่ตัวฟังก์ชัน
-- ถ้าข้อนี้ผ่าน แปลว่าตารางปกติ ปัญหาอยู่ในโค้ดของฟังก์ชัน
begin;
insert into accidents(
  incident_datetime, recorded_at, accident_code,
  party1, party2, place, road, subdistrict, district, province,
  cause, latitude, longitude, images, verify_status)
values (
  now(), now(), 'TEST-ROLLBACK',
  '{"status":"ผู้ขับขี่","passengers":[]}'::jsonb, '{"status":"ไม่มี"}'::jsonb,
  'ทดสอบระบบ', 'ถนนทดสอบ', 'ปากน้ำโพ', 'เมืองนครสวรรค์', 'นครสวรรค์',
  'ทดสอบ', 15.7047, 100.1372, '[]'::jsonb, 'รอตรวจสอบ');
select 'เพิ่มแถวตรง ๆ ผ่าน' as ผลข้อ3;
rollback;

-- ============================================================
-- หมายเหตุ
-- ============================================================
-- rollback ด้านบนคือตัวที่ทำให้แถวทดสอบไม่ค้างในระบบ
-- ถ้าเผลอลบบรรทัดนั้นออก จะมีเคสรหัส TEST-ROLLBACK โผล่ในสถิติจริง
--
