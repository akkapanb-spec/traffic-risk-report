-- รันไฟล์นี้เมื่อไรก็ได้ ระบบจะหยุดโพสต์ขึ้นเพจทันที
-- ทุกตัวส่งเช็กสวิตช์นี้ก่อนยิงทุกครั้ง จึงไม่ต้องไปหยุดงานตามเวลาทีละตัว
--
-- ไม่ลบอะไร ไม่ยกเลิกโทเคน โพสต์ที่ขึ้นเพจไปแล้วยังอยู่
-- อยากลบโพสต์ที่ขึ้นไปแล้ว ต้องลบจากหน้าเพจเอง
-- อยากเปิดกลับ รันไฟล์ fb_0_on.sql  ห้ามใช้ fb_2c_first.sql เพราะไฟล์นั้นโพสต์จริงอีกหนึ่งโพสต์
--
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์

update bs_settings
   set val = 'false'::jsonb,
       updated_at = now()
 where key = 'fbEnabled';

-- ตรวจ  ต้องได้ false
select val as สวิตช์เฟซบุ๊ก
  from bs_settings
 where key = 'fbEnabled';

