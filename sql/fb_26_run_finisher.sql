-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- ------------------------------------------------------------
-- ทำไมต้องสั่งเอง
-- ------------------------------------------------------------
-- ตัวสานต่อถูกตั้งให้วิ่งทุกนาทีโดยงานตามเวลา
-- ถ้ามันพังตอนทำงาน งานตามเวลาจะเงียบ ไม่มีที่ไหนแสดงข้อผิดพลาดให้เห็น
-- สั่งเองจากหน้านี้ ถ้าพังจะขึ้นแดงพร้อมเหตุผลทันที ซึ่งเป็นสิ่งที่เราต้องการ
--
-- ไฟล์นี้อาจทำให้มีโพสต์ขึ้นวอลล์ ถ้ามีงานค้างรออยู่จริง
-- ซึ่งก็คือสิ่งที่เราพยายามให้เกิดอยู่แล้ว ไม่ได้สร้างของใหม่เกินจากที่ยิงไปแล้ว
--
-- ------------------------------------------------------------
-- อ่านผลอย่างไร
-- ------------------------------------------------------------
-- ขึ้นแดง                      เจอต้นเหตุ ส่งข้อความแดงมาให้ดูทั้งบรรทัด
-- ตารางขึ้น ขั้น เป็น feed      สานต่อสำเร็จ รออีกนาทีแล้วดูวอลล์
-- ตารางขึ้น ขั้น เป็น photo     ยังไม่ได้รหัสรูป ดูช่องคำตอบของรูปว่าเฟซบุ๊กว่าอย่างไร
-- ไม่มีแถวเลย                   ไม่มีอะไรค้าง แปลว่าการยิงครั้งก่อนไม่ได้จองที่ไว้

select fb_finish_posts(5) as ผลการสานต่อ;

-- คำสั่งสุดท้ายคือสิ่งที่ตัวแก้ไขจะแสดงให้เห็น
select
  s.stage                                                           as ขั้น,
  s.kind || ' ' || s.ref_id                                         as เรื่อง,
  to_char(s.posted_at at time zone 'Asia/Bangkok', 'DD/MM HH24:MI') as เวลา,
  s.req_id                                                          as เลขคำขอรูป,
  r1.status_code                                                    as ผลอัปโหลดรูป,
  left(coalesce(r1.content, r1.error_msg, ''), 150)                 as คำตอบของรูป,
  r2.status_code                                                    as ผลโพสต์,
  left(coalesce(r2.content, r2.error_msg, ''), 150)                 as คำตอบของโพสต์,
  left(coalesce(s.note, ''), 120)                                   as บันทึกของเรา
from fb_sent s
left join net._http_response r1 on r1.id = s.req_id
left join net._http_response r2 on r2.id = s.req2_id
where coalesce(s.stage, '') <> 'done'
   or s.posted_at > now() - interval '120 minutes'
order by s.posted_at desc
limit 6;

