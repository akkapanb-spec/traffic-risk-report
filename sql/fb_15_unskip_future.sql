-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- ------------------------------------------------------------
-- เรื่องที่เกิดขึ้นจริง
-- ------------------------------------------------------------
-- ประกาศงานชุนหงษ์ถูกกรอกไว้ 22 ก.ย. 19:01 ตั้งเวลาเริ่ม 24 ก.ย. 16:00
-- วันที่ 23 ก.ย. 05:52 ไฟล์ fb_3c ถูกรัน และท้ายไฟล์นั้นจดประกาศ
-- ทุกใบที่มีอยู่ในตารางว่า มีอยู่ก่อนเปิดใช้เฟซบุ๊ก ไม่โพสต์ย้อนหลัง
--
-- ตัวกันของค้างนั้นถูกต้องสำหรับประกาศที่ผ่านไปแล้ว
-- แต่มันไม่ได้ดูเวลาเลย จึงเหมาไปถึงใบที่ยังไม่เกิดขึ้นด้วย
-- งานชุนหงษ์จึงถูกปิดปากไว้ตั้งแต่วันก่อนหน้า โดยไม่มีใครรู้
-- ไม่เกี่ยวกับไฟล์ 9 ที่รัน 24 ก.ย. 16:01 เลย ใบนั้นจดไปแล้วหนึ่งวันเต็ม
--
-- ------------------------------------------------------------
-- ไฟล์นี้แก้อะไร
-- ------------------------------------------------------------
-- ลบเฉพาะแถวที่เข้าเงื่อนไขครบสามข้อ
--   หนึ่ง  เป็นประกาศ
--   สอง   ไม่เคยยิงออกไปเลย  req_id ว่าง  จึงไม่มีโพสต์ซ้ำแน่นอน
--   สาม   เวลาเริ่มยังอยู่ข้างหน้า  คือยังไม่สายที่จะประกาศ
--
-- แถวของงานที่ผ่านไปแล้วไม่ถูกแตะ ของเก่าจะไม่ย้อนขึ้นเพจ
-- งานชุนหงษ์เองก็ไม่กลับมา เพราะจบไปตั้งแต่สามทุ่มวันที่ 24

delete from fb_sent s
 where s.kind = 'advisory'
   and s.req_id is null
   and exists (
     select 1 from traffic_advisories t
      where t.id::text = s.ref_id
        and t.closed_at is null
        and t.starts_at > now()
   );

-- ตรวจ  ประกาศที่ยังไม่ถึงเวลาเริ่ม ต้องไม่เหลือคำว่า จดไว้แล้ว อีก
select
  t.id                                                              as รหัส,
  left(coalesce(t.title, ''), 34)                                   as เรื่อง,
  to_char(t.starts_at at time zone 'Asia/Bangkok', 'DD/MM HH24:MI') as เริ่ม,
  case when exists (select 1 from fb_sent s
                     where s.kind = 'advisory' and s.ref_id = t.id::text)
       then 'จดไว้แล้ว ไม่ขึ้นเพจ' else 'รอขึ้นเพจ' end              as สถานะ
from traffic_advisories t
where t.closed_at is null
  and t.ends_at >= now()
order by t.starts_at;

