-- งานตั้งเวลายังเดินตามปกติ แค่หาปลายทางไม่เจอจึงไม่ส่งอะไรออกไป
-- เปิดกลับเมื่อไรก็ได้ด้วยคำสั่งท้ายไฟล์ ไม่ต้องหารหัสกลุ่มใหม่
