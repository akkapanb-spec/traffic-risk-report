-- สิ่งที่ค้างระหว่างพัก ไม่หายไปไหน
--   จุดเสี่ยงซ้ำคิดจากข้อมูลสดทุกรอบ เปิดกลับมาก็ได้ตัวเลขล่าสุดทันที
--   ส่วนผู้เสียชีวิตที่บันทึกใหม่ระหว่างนี้ จะค้างรอส่งไว้
--   พอเปิดกลับจะทยอยส่งรอบละไม่เกิน 3 ราย
