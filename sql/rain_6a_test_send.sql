-- ทดลองส่งข้อความแจ้งเตือนฝนของจริง ไปยังปลายทางเดียวที่เลือกเอง
-- ถ้ามี $0 ต่อท้ายไฟล์ ให้ลบออกก่อนกด Run
--
-- ไฟล์นี้ไม่แตะระบบอัตโนมัติเลย
--   ไม่บันทึกลง line_sent จึงไม่กินสิทธิ์ข้อความจริงของวันนี้
--   ไม่แตะสวิตช์ ไม่แตะเกณฑ์ ไม่แตะงานตั้งเวลา
--   ส่งไปปลายทางที่พิมพ์ไว้ข้างล่างที่เดียว ไม่ได้ส่งเข้าทุกกลุ่ม
--
-- ข้อความที่ส่งคือข้อความเดียวกับที่ระบบจะส่งจริง คัดลอกมาตรง ๆ
-- ต่างกันแค่บรรทัดแรกที่เติมคำว่า ทดสอบ ไว้ให้รู้ว่าไม่ใช่ของจริง
--
-- ==========================================================
-- แก้บรรทัดเดียว  ใส่รหัสปลายทางระหว่างเครื่องหมายคำพูด
-- ==========================================================
-- รหัสกลุ่มขึ้นต้นด้วยตัว C   รหัสคนขึ้นต้นด้วยตัว U
-- วิธีหารหัสกลุ่มทดสอบ  สร้างกลุ่มไลน์ใหม่ที่มีแต่ตัวเอง แล้วเชิญบอทเข้ากลุ่ม
-- บอทจะตอบรหัสกลุ่มออกมาให้ทันที เอามาวางตรงนี้

with ปลายทาง as (
  select 'วางรหัสตรงนี้'::text as id
)
select
  case
    when id = 'วางรหัสตรงนี้' or left(id, 1) not in ('C', 'U')
      then 'ยังไม่ได้ใส่รหัสปลายทาง ยังไม่ได้ส่งอะไรออกไป'
    else 'ส่งแล้ว หมายเลขคำขอ ' || coalesce(line_push(id, array_to_string(array[
        '🧪 ทดสอบระบบ ไม่ใช่เหตุการณ์จริง',
        '',
        '🌧️ เตือนฝนกำลังเข้าเขตเมืองนครสวรรค์',
        'เรดาร์ตรวจพบกลุ่มฝนในรัศมี 8 กม. รอบแยกเดชาติวงศ์',
        '',
        'ช่วงอันตรายที่สุด',
        'คือไม่กี่นาทีแรกที่ฝนเริ่มตก',
        '',
        '💧 น้ำผสมกับคราบน้ำมันบนผิวถนน',
        'กลายเป็นฟิล์มทำให้ถนนลื่น',
        'ยางเกาะถนนได้น้อยลงมาก',
        '⚠️ ทั้งที่ถนนยังดูเหมือนแค่ชื้น',
        '',
        'โปรดใช้ความระมัดระวังและลดความเร็ว',
        'ควรเพิ่มระยะห่างจากรถคันหน้าเป็น 2️⃣ เท่า',
        '',
        '👮 ด้วยความปรารถนาดี น้องจราจรชอนตะวัน'
      ], chr(10)))::text, 'ไม่สำเร็จ')
  end as ผล
from ปลายทาง;
