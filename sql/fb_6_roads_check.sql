-- ตรวจชื่อถนนที่บันทึกไว้จริง  อ่านอย่างเดียว ไม่แก้ไขอะไรเลย
-- ============================================================
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- ทำไมต้องดู
-- การ์ดสรุปรายสัปดาห์ใบแรกที่วาดจากข้อมูลจริง ขึ้นถนนซ้ำกันสองอันดับ
-- อันดับหนึ่งเขียนว่า พหลโยธิน  อันดับสองเขียนว่า ถนนพหลโยธิน
-- เป็นถนนสายเดียวกัน แต่พิมพ์ต่างกันตอนบันทึก ระบบจึงนับแยกกัน
-- ขึ้นเพจแบบนี้คนอ่านจะงง และตัวเลขอันดับก็ผิดไปด้วย
--
-- ก่อนจะรวมชื่อ ต้องเห็นของจริงก่อนว่ามีกี่แบบ เขียนกันว่าอย่างไรบ้าง
-- เดาแล้วเขียนกฎรวมไปเลยจะพลาด เพราะถนนสายเดียวกันมีทั้งชื่อและเลขทางหลวง
-- เช่น ถนนพหลโยธิน กับ ทล.1 คือสายเดียวกัน ซึ่งกฎตัดคำว่า ถนน ออก ไม่ช่วยอะไร
--
-- ผลที่ได้ให้ส่งกลับมาทั้งตาราง จะได้เขียนกฎรวมชื่อจากของจริง

select
  coalesce(nullif(btrim(a.road), ''), 'ไม่ได้กรอก')                          as ชื่อถนนที่บันทึกไว้,
  count(*)                                                                    as จำนวนครั้ง,
  count(*) filter (where a.incident_datetime >= now() - interval '90 days')   as ใน90วันล่าสุด,
  min(a.incident_datetime at time zone 'Asia/Bangkok')::date                  as ครั้งแรก,
  max(a.incident_datetime at time zone 'Asia/Bangkok')::date                  as ครั้งล่าสุด
from accidents a
group by 1
order by 2 desc;

