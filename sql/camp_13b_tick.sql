-- ใช้ในโหมดตรวจทุกนาที  งานตามเวลาตั้งถี่กว่านาทีละครั้งไม่ได้
-- จึงรวมสามขั้นไว้ในรอบเดียว และเรียงลำดับให้คำตอบของรอบก่อนถูกเก็บก่อนเสมอ
--
--   หนึ่ง  เก็บคำตอบจากไลน์ของคำถามที่ยิงไปเมื่อนาทีที่แล้ว  คำตอบมาถึงภายในไม่กี่วินาที
--   สอง   ตัดสินรางวัลจากผลที่เพิ่งเก็บ
--   สาม   ยิงคำถามรอบใหม่  คำขอออกไปจริงหลังรอบนี้จบ แล้วนาทีหน้าจะมาเก็บ
--
-- ถ้ายิงก่อนแล้วเก็บในรอบเดียวกัน จะเก็บไม่เจออะไรเลย
-- เพราะ pg_net ส่งคำขอออกไปหลังทรานแซกชันปิดเท่านั้น
--
-- ตัวตัดสินรางวัลไม่ส่งข้อความ และไม่ให้สิทธิ์ซ้ำ รันทุกนาทีจึงไม่มีผลข้างเคียง
--
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์

create or replace function camp_tick()
returns void
language plpgsql
volatile
security definer
set search_path = public
as $fn$
begin
  perform camp_check_collect();
  perform camp_award();
  perform camp_check_fire();
end;
$fn$;

revoke execute on function camp_tick() from public, anon, authenticated;

-- ตรวจ  ต้องได้ 1
select (select count(*) from pg_proc where proname = 'camp_tick') as ฟังก์ชัน;

