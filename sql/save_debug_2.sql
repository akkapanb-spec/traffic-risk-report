-- ============================================================
-- หาบรรทัดที่แปลงข้อความเป็น JSON ในโค้ดที่รันอยู่จริง
-- ============================================================
-- ไฟล์นี้ "อ่านอย่างเดียว" ไม่สร้าง ไม่แก้ ไม่ลบ ไม่เพิ่มอะไรเลย
-- ไม่ต้องใช้ token ไม่ต้องแก้อะไรก่อนรัน
--
-- ตรวจก่อนกด Run: บรรทัดแรกของช่อง editor ต้องเป็นเส้น ==== ชุดนี้
--
-- ไฟล์นี้เขียนโดยเลี่ยงวงเล็บปีกกาทั้งหมด
-- เพราะเครื่องนี้มีอะไรบางอย่างแทรกแบ็กสแลชหน้าวงเล็บปีกกาปิด
-- ถ้าไม่มีปีกกาเลย ก็ไม่มีอะไรให้แทรก
--
-- ที่มา
--   คำสั่งบันทึกอุบัติเหตุพังด้วย invalid input syntax for type json
--   ผมไล่อ่านจากไฟล์ในโปรเจกต์แล้วไม่พบจุดที่แปลงข้อความเป็น JSON เลย
--   แต่ไฟล์ในโปรเจกต์เป็นบันทึกการแก้ ไม่ใช่สภาพปัจจุบันของฐานข้อมูล
--   ไฟล์นี้จึงไปดูของจริงที่รันอยู่
-- ============================================================

-- ============================================================
-- 1) มีคำสั่งบันทึกกี่ตัว และรับพารามิเตอร์แบบไหนบ้าง
-- ============================================================
-- ถ้ามีมากกว่าหนึ่งแถว แปลว่ามีของเก่าค้างอยู่และอาจถูกเรียกใช้แทนตัวใหม่
select p.oid::regprocedure as คำสั่งบันทึกที่มีอยู่
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
 where n.nspname = 'public' and p.proname = 'officer_save_accident';

-- ============================================================
-- 2) บรรทัดในโค้ดจริงที่แปลงข้อความเป็น JSON
-- ============================================================
-- นี่คือคำตอบที่ต้องการที่สุด ถ้ามีแถวออกมา แสดงว่าเจอตัวการแล้ว
-- ถ้าไม่มีแถวเลย แปลว่าไม่ได้พังในคำสั่งนี้ ให้ดูข้อ 3 กับ 4 ต่อ
select t.ln as บรรทัดที่, t.txt as โค้ดบรรทัดนั้น
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
 cross join lateral unnest(string_to_array(p.prosrc, chr(10)))
       with ordinality as t(txt, ln)
 where n.nspname = 'public' and p.proname = 'officer_save_accident'
   and t.txt ~ '::json([^b]|$)|to_json|json_build|json_agg'
 order by t.ln;

-- ============================================================
-- 3) ทริกเกอร์บนตารางที่คำสั่งบันทึกไปเขียนข้อมูลลง
-- ============================================================
-- ก่อนหน้านี้ผมตรวจแค่ตารางอุบัติเหตุ ลืมตรวจตารางผู้เสียชีวิตและผู้บาดเจ็บ
-- ทั้งที่คำสั่งบันทึกเขียนลงทั้งสามตาราง
select c.relname as ตาราง, tg.tgname as ชื่อทริกเกอร์,
       p.proname as ฟังก์ชันที่ทริกเกอร์เรียก
  from pg_trigger tg
  join pg_class c on c.oid = tg.tgrelid
  join pg_proc p on p.oid = tg.tgfoid
 where not tg.tgisinternal
   and c.relname in ('accidents', 'deaths', 'injuries');

-- ============================================================
-- 4) ฟังก์ชันอื่นทั้งหมดที่แปลงข้อความเป็น JSON
-- ============================================================
-- เผื่อว่าตัวที่พังคือฟังก์ชันที่ถูกเรียกต่อจากคำสั่งบันทึกอีกทอด
select p.proname as ฟังก์ชันที่มีการแปลงเป็น_json
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
 where n.nspname = 'public'
   and p.prosrc ~ '::json([^b]|$)'
 order by 1;

-- ============================================================
-- 5) ชนิดของคอลัมน์ในตารางอุบัติเหตุ
-- ============================================================
-- คอลัมน์ที่เป็น json เฉย ๆ จะเข้มงวดกว่า jsonb และเป็นเบาะแสได้
select column_name as คอลัมน์, data_type as ชนิด
  from information_schema.columns
 where table_schema = 'public' and table_name = 'accidents'
   and data_type in ('json', 'jsonb', 'text')
 order by ordinal_position;

