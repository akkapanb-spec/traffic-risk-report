-- สั่งให้แจ้งเตือนจุดเสี่ยงซ้ำใหม่อีกครั้ง
-- ถ้ามีอักขระแปลกปลอมต่อท้ายบรรทัดสุดท้าย ให้ลบออกก่อนกด Run
--
-- ทำไมระบบถึงเงียบ
--   ตัวกันส่งซ้ำจำว่าเคยส่งชุดตัวเลขนี้ไปแล้วเมื่อ 22 และ 23 ส.ค.
--   แต่ช่วงนั้นโควตาข้อความของบัญชีไลน์หมด ไลน์ปฏิเสธทั้งฉบับ
--   ระบบบันทึกว่าส่งแล้วทั้งที่ไม่มีใครได้รับ แล้วจึงไม่ยอมส่งซ้ำอีกเลย
--
--   ตัวตรวจที่เพิ่งติดตั้งจะกันเรื่องนี้ในอนาคต แต่ย้อนกลับไปแก้ของเก่าไม่ได้
--   เพราะคำตอบของไลน์ถูกลบไปก่อนที่ตัวตรวจจะเกิด สองแถวนั้นจึงค้างเป็น ไม่ทราบผล
--
-- ไฟล์นี้ทำอย่างเดียว คือลบบันทึกสองแถวนั้นทิ้ง
-- งานตั้งเวลาที่รันทุกห้านาทีจะเห็นว่ายังไม่เคยส่ง แล้วส่งเองภายในห้านาที
-- ไม่ต้องสั่งส่งเอง ไม่ต้องแตะข้อความ ไม่ต้องแตะเกณฑ์

delete from line_sent
where kind = 'hotspot'
  and detail like 'ไม่ทราบผล%'
  and sent_at >= timestamptz '2026-08-22 00:00:00+07';

-- ==========================================================
-- ตรวจผล  คำสั่งสุดท้ายคำสั่งเดียวที่จะแสดงผล
-- ==========================================================

select 'บันทึกที่เหลืออยู่' as รายการ,
       coalesce((select string_agg(to_char(sent_at at time zone 'Asia/Bangkok', 'DD/MM HH24:MI'), '   ' order by sent_at desc)
                 from line_sent where kind = 'hotspot'), 'ไม่เหลือแล้ว') as ผล
union all
select 'งานตั้งเวลา',
       coalesce((select jobname || ' = ' || schedule from cron.job where jobname = 'line-hotspot'), 'ไม่พบ')
union all
select 'จะส่งเมื่อไร', 'ภายในห้านาทีข้างหน้า โดยงานตั้งเวลาเอง'
union all
select 'ผู้รับ', (select count(*)::text from line_targets where enabled and target_type = 'group')
                 || ' กลุ่ม';
