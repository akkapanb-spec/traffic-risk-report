-- ============================================================
-- ตรวจว่าแจ้งเตือนไลน์เดินถึงไหนแล้ว
-- ============================================================
-- ไฟล์นี้ "อ่านอย่างเดียว" ไม่สร้าง ไม่แก้ ไม่ลบ ไม่ส่งอะไรเข้าไลน์
-- ไม่ต้องใช้ token ไม่ต้องแก้อะไรก่อนรัน มีคำสั่งเดียว
--
-- ตรวจก่อนกด Run: บรรทัดแรกของช่อง editor ต้องเป็นเส้น ==== ชุดนี้
-- ถ้ามี $0 ค้างอยู่บรรทัดสุดท้าย ให้ลบทิ้งก่อนกด Run
-- ไฟล์นี้ไม่มีวงเล็บปีกกาเลยแม้แต่ตัวเดียว
--
-- อาการ
--   ซ่อมฟังก์ชันแล้ว แต่กลุ่มไลน์ยังเงียบสนิท
--   ทั้งที่ควรจะเริ่มไล่ส่งผู้เสียชีวิตที่ค้างอยู่
--
-- สิ่งที่ตรวจ เรียงตามลำดับที่ข้อมูลต้องเดินผ่าน
--   1 งานตั้งเวลาเดินจริงไหม และรอบล่าสุดจบด้วยผลอะไร
--   2 มีปลายทางที่เปิดรับอยู่ไหม ถ้าไม่มี ส่งเท่าไรก็ไม่ถึงใคร
--   3 มีบันทึกว่าส่งอะไรไปแล้วบ้าง
--   4 ยังมีผู้เสียชีวิตค้างรอส่งกี่ราย
--
-- จุดไหนที่ตัวเลขขาดตอน คือจุดที่ติด
-- ============================================================

select '1 งานตั้งเวลา' as ลำดับ,
       j.jobname || ' เดิน ' || j.schedule ||
       case when j.active then ' สถานะเปิด' else ' สถานะปิดอยู่' end as รายละเอียด
  from cron.job j
 where j.jobname like 'line%'

union all
select '2 ผลรอบล่าสุด',
       coalesce(r.status, 'ไม่มีข้อมูล') || ' — ' ||
       coalesce(nullif(btrim(r.return_message), ''), 'ไม่มีข้อความ') ||
       ' เมื่อ ' || to_char(timezone('Asia/Bangkok', r.start_time), 'HH24:MI:SS')
  from cron.job_run_details r
  join cron.job j on j.jobid = r.jobid
 where j.jobname like 'line%'
   and r.start_time > now() - interval '2 hours'

union all
select '3 ปลายทางที่เปิดรับ',
       t.target_type || ' · ' || coalesce(t.label, 'ไม่มีชื่อ') ||
       case when t.enabled then ' · เปิด' else ' · ปิด' end ||
       case when t.want_death then ' · รับข่าวผู้เสียชีวิต' else ' · ไม่รับข่าวผู้เสียชีวิต' end
  from line_targets t

union all
select '4 เคยส่งอะไรไปแล้ว',
       s.kind || ' จำนวน ' || count(*)::text || ' ครั้ง'
  from line_sent s group by s.kind

union all
select '5 ผู้เสียชีวิตค้างรอส่ง',
       count(*)::text || ' ราย จากทั้งหมด ' ||
       (select count(*)::text from deaths) || ' ราย'
  from deaths d
 where not exists (
   select 1 from line_sent s where s.kind = 'death' and s.ref_id = d.id::text)

union all
select '6 ในจำนวนที่ค้าง เป็นรายที่เข้าเกณฑ์แจ้ง',
       count(*)::text || ' ราย ที่เสียชีวิตในที่เกิดเหตุ'
  from deaths d
 where btrim(coalesce(d.col_g, '')) = 'เสียชีวิตที่เกิดเหตุ'
   and not exists (
     select 1 from line_sent s where s.kind = 'death' and s.ref_id = d.id::text)

order by 1, 2;

-- ============================================================
-- อ่านผลยังไง
-- ============================================================
-- ไม่มีแถวลำดับ 1  = งานตั้งเวลาหายไป ต้องตั้งใหม่
-- ลำดับ 2 ขึ้น failed = ยังมี error อยู่ ให้ส่งข้อความที่เห็นมาให้ดู
-- ลำดับ 2 ไม่มีเลย   = งานยังไม่เคยเดินในสองชั่วโมงที่ผ่านมา
-- ไม่มีแถวลำดับ 3  = ไม่มีปลายทาง ต้องเพิ่มกลุ่มก่อน ส่งเท่าไรก็ไม่ถึงใคร
-- ลำดับ 4 ไม่มี death = ยังไม่เคยส่งข่าวผู้เสียชีวิตสำเร็จเลยสักครั้ง
-- ลำดับ 6 เป็น 0   = ไม่มีใครเข้าเกณฑ์ เพราะข้อมูลเก่าที่นำเข้าไม่ได้ระบุว่าเสียชีวิตที่ใด
--                    กรณีนี้เงียบคือถูกต้องแล้ว ไม่ต้องแก้อะไร
-- ============================================================
