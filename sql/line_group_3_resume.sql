--       ตัวนี้ยังไม่เคยส่งเลย จึงจะออกทันทีที่เปิด จำนวน 2 จุดตามที่พรีวิวไว้
--       ถ้ายังไม่อยากให้ตัวนี้ออกพร้อมกัน ให้หยุดงานตั้งเวลาของมันไว้ก่อน
--       คำสั่งอยู่ท้ายไฟล์
--
--   ทั้งสองฉบับเข้ากลุ่มที่มีประชาชนอยู่ ไม่ใช่การทดลอง
