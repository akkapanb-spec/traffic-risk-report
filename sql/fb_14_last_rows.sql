-- ถ้าฐานข้อมูลไม่ให้อ่านตารางนั้น ทั้งคำสั่งจะล้ม แล้วหน้าจอจะไม่แสดงอะไร
-- ซึ่งหน้าตาเหมือนกับกรณีที่ไม่มีข้อมูลจริง ๆ แยกไม่ออกจากตรงนี้
-- ไฟล์ 13 เพิ่งบอกว่ามี 109 แถว แปลว่าที่ไฟล์ 2b เงียบ คือคำสั่งล้ม ไม่ใช่ไม่มีข้อมูล
--
-- ไฟล์นี้จึงอ่าน fb_sent ตัวเดียว ไม่ต่อกับอะไรเลย
--
-- ------------------------------------------------------------
-- อ่านผลอย่างไร
-- ------------------------------------------------------------
-- ช่อง ยิงออกไปหรือยัง คือหัวใจ
--   ยิงแล้ว      เคยส่งคำขอไปหาเฟซบุ๊กจริง ต้องไปดูที่เพจว่าขึ้นไหม
--   ไม่ได้ยิง    แค่จดไว้ว่าไม่ต้องส่ง ไม่เคยมีคำขอออกไป
-- ช่อง บันทึกของเรา จะบอกเหตุผลของแถวที่ไม่ได้ยิง

select
  s.kind                                                            as ชนิด,
  s.ref_id                                                          as รหัสอ้างอิง,
  to_char(s.posted_at at time zone 'Asia/Bangkok', 'DD/MM HH24:MI') as เวลาที่จด,
  case when s.req_id is null then 'ไม่ได้ยิง' else 'ยิงแล้ว' end     as ยิงออกไปหรือยัง,
  s.ok                                                              as สำเร็จ,
  left(coalesce(s.note, ''), 90)                                    as บันทึกของเรา
from fb_sent s
order by s.posted_at desc, s.id desc
limit 12;

