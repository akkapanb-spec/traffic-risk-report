-- ทดสอบข้อความตอนชวนครบ โดยไม่ต้องรอให้มีคนชวนครบจริง
-- รันหลัง camp_9_fix_msg.sql
-- ถ้ามี $0 ต่อท้ายไฟล์ ให้ลบออกก่อนกด Run
--
-- ทำไมต้องทดสอบท่อนนี้แยก
--   ท่อน ครบแล้ว ติดต่อรับของรางวัล อยู่หลังเงื่อนไข ชวนครบ 5 คน
--   ตอนนี้คนที่มากที่สุดชวนได้ 1 คน ท่อนนั้นจึงไม่เคยถูกรันเลย
--   และมันคือท่อนเดียวกับที่เพิ่งพังด้วยเรื่อง malformed array literal
--   ถ้าไม่ทดสอบตอนนี้ คนแรกที่ทำสำเร็จจริงจะเป็นคนแรกที่รันโค้ดท่อนนี้
--
-- วิธีทดสอบ
--   ลดเกณฑ์ลงเหลือ 1 คนชั่วคราว เรียกข้อความเก็บไว้ แล้วคืนค่าเป็น 5 ทันที
--   ทั้งไฟล์อยู่ในทรานแซกชันเดียว ถ้าพังตรงไหนค่าจะย้อนกลับเป็น 5 เองอัตโนมัติ
--   ไม่มีทางที่เกณฑ์จะค้างอยู่ที่ 1

-- ลดเกณฑ์ชั่วคราว
update bs_settings set val = to_jsonb(1) where key = 'campNeedFriends';

-- เก็บข้อความไว้ก่อน ต้องเก็บตอนที่เกณฑ์ยังเป็น 1
create temp table camp_test_msg as
select coalesce(display_name, ref_code)  as ผู้เข้าร่วม,
       camp_friend_count(line_user_id)   as ชวนได้,
       camp_msg_status(line_user_id)     as ข้อความที่จะได้รับ,
       created_at
from camp_members;

-- คืนค่าเกณฑ์กลับเป็น 5 ทันที ก่อนแสดงผล
update bs_settings set val = to_jsonb(5) where key = 'campNeedFriends';

-- คำสั่งสุดท้ายคำสั่งเดียวที่จะแสดงผล
-- แถวของคนที่ชวนได้ตั้งแต่ 1 คนขึ้นไป ต้องมีบรรทัด ครบแล้ว ติดต่อรับ อยู่ด้วย
select ผู้เข้าร่วม,
       ชวนได้,
       case when position('ครบแล้ว' in ข้อความที่จะได้รับ) > 0
            then 'มีท่อนครบแล้ว ผ่าน' else 'ไม่มีท่อนครบแล้ว' end as ผลการทดสอบ,
       ข้อความที่จะได้รับ,
       (select camp_cfg('campNeedFriends', 'ไม่พบ')) as เกณฑ์ตอนนี้ต้องเป็น5
from camp_test_msg
order by created_at;
