insert into line_targets (label, target_id, target_type,
                          want_death, want_daily, want_weekly, enabled, note)
values ('กลุ่มแจ้งเตือนอุบัติเหตุ สภ.เมืองนครสวรรค์',
        'C81363b18be5a1b0fcf5cd4d7d868e782',
        'group',
        true,    -- ผู้เสียชีวิตรายใหม่ เฉพาะที่เสียชีวิตในที่เกิดเหตุ
        false,   -- สรุปประจำวัน ปิดไว้ก่อน เปิดได้ทีหลังถ้าต้องการ
        false,   -- สรุปประจำสัปดาห์ ปิดไว้ก่อนเช่นกัน
        true,
        'ลงทะเบียน 18 ส.ค. 69 เพื่อรับแจ้งเตือนจุดเสี่ยงซ้ำและผู้เสียชีวิต')
on conflict (target_id) do update
   set label       = excluded.label,
       target_type = excluded.target_type,
       want_death  = excluded.want_death,
       enabled     = true;

-- ============================================================
-- ตรวจผลทันทีหลังรัน
-- ============================================================
select t.label      as ชื่อปลายทาง,
       t.target_type as ชนิด,
       left(t.target_id, 10) || '...' as รหัส,
       case when t.enabled then 'เปิด' else 'ปิด' end as สถานะ,
       case when t.want_death then 'รับ' else 'ไม่รับ' end as ข่าวผู้เสียชีวิต
  from line_targets t
 order by t.target_type, t.label;

