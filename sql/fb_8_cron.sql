-- ตั้งเวลาไว้ก่อนจึงปลอดภัย งานจะเดินแต่ไม่ส่งอะไรออกไป
-- พอเปิดสวิตช์เมื่อไหร่ ของถึงจะเริ่มขึ้นเพจ
--
-- ------------------------------------------------------------
-- เวลาในตารางนี้เป็นเวลามาตรฐานสากล ไม่ใช่เวลาไทย
-- ------------------------------------------------------------
-- pg_cron อ่านเป็น UTC บวกเจ็ดชั่วโมงถึงจะเป็นเวลาบ้านเรา
-- เขียนเวลาไทยลงไปตรง ๆ จะกลายเป็นส่งตอนตีห้าของวันรุ่งขึ้น
--
-- ------------------------------------------------------------
-- ทำไมถึงไม่ถี่เท่าไลน์
-- ------------------------------------------------------------
-- ไลน์เป็นวงจำกัดและกดออกได้ เพจเป็นสาธารณะถาวร ค้นเจอด้วยกูเกิล
-- โพสต์ถี่เกินไปหน้าเพจจะกลายเป็นรายการแจ้งเหตุ ไม่มีใครตามอ่าน
-- ข่าวเสียชีวิตจึงทุกสิบนาที ไม่ใช่ทุกห้านาทีแบบไลน์
-- และจุดเสี่ยงซ้ำสัปดาห์ละครั้ง เพราะเคยมีบทเรียนจากไลน์มาแล้ว
-- ว่าหน้าต่างเลื่อนบวกกุญแจกันซ้ำที่ฝังตัวเลขไว้ จะส่งซ้ำเองแม้ไม่มีใครกรอกข้อมูล
-- ความถี่ของตัวตั้งเวลาคือสิ่งเดียวที่คุมได้ว่าจะส่งบ่อยแค่ไหน

-- ==========================================================
-- 1  ข่าวอุบัติเหตุเสียชีวิต  ทุกสิบนาที
-- ==========================================================
-- เหลื่อมจากงานของไลน์ที่วิ่งทุกห้านาที จะได้ไม่ชนกัน
-- ตัวมันเองมองย้อนหลังแค่ 48 ชั่วโมง ของเก่ากว่านั้นไม่ถูกหยิบมาโพสต์

select cron.schedule('fb-deaths', '2-59/10 * * * *', 'select fb_send_deaths(3, 48)');

-- ==========================================================
-- 2  ประกาศเส้นทางเลี่ยง  ทุกสิบห้านาที
-- ==========================================================
-- พวกก่อสร้าง ปิดถนน ขบวน กิจกรรม น้ำท่วม เป็นเรื่องที่คนต้องรู้ก่อนออกจากบ้าน
-- จึงถี่กว่าสรุป แต่ไม่ถี่เท่าข่าวเสียชีวิต

select cron.schedule('fb-advisory', '7-59/15 * * * *', 'select fb_send_advisories(3)');

-- ==========================================================
-- 3  จุดอุบัติเหตุซ้ำ  จันทร์ 10:00 น. เวลาไทย
-- ==========================================================
-- ไลน์ส่งเรื่องเดียวกันตอนเก้าโมง เว้นหนึ่งชั่วโมงไม่ให้ซ้อนกัน

select cron.schedule('fb-hotspot', '0 3 * * 1', 'select fb_send_hotspots()');

-- ==========================================================
-- 4  สรุปสถานการณ์รายสัปดาห์  จันทร์ 09:30 น. เวลาไทย
-- ==========================================================
-- สัปดาห์หนึ่งขึ้นได้โพสต์เดียว ตัวกันซ้ำอยู่ในตาราง fb_sent ไม่ใช่ที่ความถี่
-- ต่อให้งานนี้เดินซ้ำกี่รอบก็ได้โพสต์เดียวอยู่ดี

select cron.schedule('fb-weekly', '30 2 * * 1', 'select fb_send_weekly(7)');

-- ==========================================================
-- 5  ตรวจ  ดูตารางงานทั้งหมดที่ตั้งไว้
-- ==========================================================
-- ช่อง สวิตช์ ต้องเป็น false ตอนนี้ ถ้าเป็น true แปลว่าของขึ้นเพจแล้ว

select
  j.jobname                                     as ชื่องาน,
  j.schedule                                    as ตารางเวลาแบบสากล,
  j.active                                      as เปิดใช้,
  j.command                                     as คำสั่ง,
  (select val #>> array[]::text[] from bs_settings where key = 'fbEnabled') as สวิตช์เฟซบุ๊ก
from cron.job j
where j.jobname like 'fb-%'
order by j.jobname;

