select cron.unschedule('line-serious');

-- ตรวจว่าเหลืองานอะไรเดินอยู่บ้าง
select j.jobname as งานตั้งเวลา,
       j.schedule as รอบการเดิน,
       case when j.active then 'เปิด' else 'ปิด' end as สถานะ
  from cron.job j
 where j.jobname like 'line%'
 order by j.jobname;

