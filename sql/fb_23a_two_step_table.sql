-- ช่องที่เพิ่ม
-- ------------------------------------------------------------
-- stage         ขั้นที่ค้างอยู่  photo คือรอรหัสรูป  feed คือรอผลโพสต์  done คือจบแล้ว
-- pending_text  ข้อความที่จะโพสต์ ต้องเก็บไว้ เพราะจังหวะสองอยู่คนละทรานแซกชัน
--               สร้างใหม่ตอนนั้นไม่ได้ ข้อมูลอาจเปลี่ยนไปแล้วและจะได้ข้อความคนละอัน
-- photo_id      รหัสรูปที่เฟซบุ๊กคืนมาจากจังหวะแรก
-- req2_id       เลขคำขอของจังหวะสอง แยกจาก req_id ของจังหวะแรก

alter table fb_sent add column if not exists stage        text;
alter table fb_sent add column if not exists pending_text text;
alter table fb_sent add column if not exists photo_id     text;
alter table fb_sent add column if not exists req2_id      bigint;

-- แถวที่มีอยู่เดิมทั้งหมดถือว่าจบแล้ว จะได้ไม่ถูกตัวสานต่อหยิบไปทำ
update fb_sent set stage = 'done' where stage is null;

create index if not exists fb_sent_stage_idx on fb_sent (stage) where stage <> 'done';

-- ตรวจ  ต้องไม่มีแถวไหนค้างอยู่ในขั้น photo หรือ feed เลย
select
  coalesce(stage, 'ไม่ระบุ') as ขั้น,
  count(*)                   as จำนวนแถว
from fb_sent
group by 1
order by 2 desc;

