-- ============================================================
-- อ่านคำตอบเรื่องซ่อนจากไทม์ไลน์  อ่านอย่างเดียว
-- ============================================================
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- อ่านผลอย่างไร
--   ถูกซ่อน เป็น true    เจอต้นเหตุแล้ว โพสต์ถูกซ่อนจากไทม์ไลน์ตั้งแต่สร้าง
--                        แก้ได้ด้วยคำสั่งเดียว และแก้ที่ตัวส่งไม่ให้เกิดอีก
--   ถูกซ่อน เป็น false   ไม่ใช่เรื่องนี้ ต้องไปดูที่ฝั่งเพจและสิทธิ์ของแอปแทน
--   หมดอายุ เป็น true    โพสต์ถูกตั้งเวลาให้หมดอายุ ซึ่งก็ทำให้หายจากวอลล์เหมือนกัน

select
  to_char(r.created at time zone 'Asia/Bangkok', 'DD/MM HH24:MI:SS') as เวลาที่ตอบกลับ,
  (r.content::jsonb) ->> 'is_hidden'                                 as ถูกซ่อน,
  (r.content::jsonb) ->> 'is_published'                              as เผยแพร่แล้ว,
  (r.content::jsonb) ->> 'is_expired'                                as หมดอายุ,
  (r.content::jsonb) -> 'privacy' ->> 'value'                        as ใครเห็นได้,
  (r.content::jsonb) ->> 'status_type'                               as ชนิดเรื่องราว,
  left(coalesce(r.content, r.error_msg, ''), 250)                    as คำตอบเต็ม
from net._http_response r
where coalesce(r.content, '') like '%is_hidden%'
order by r.id desc
limit 3;

