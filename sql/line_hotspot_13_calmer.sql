-- ลดความถี่การแจ้งจุดอุบัติเหตุซ้ำ
-- ถ้ามีอักขระแปลกปลอมต่อท้ายบรรทัดสุดท้าย ให้ลบออกก่อนกด Run
-- ไม่แตะฟังก์ชัน line_send_hotspots ไม่แตะถ้อยคำในข้อความ
-- แก้เฉพาะจังหวะเวลาที่เรียกฟังก์ชัน
--
-- ------------------------------------------------------------
-- ทำไมถึงแจ้งถี่
-- ------------------------------------------------------------
--
-- หนึ่ง  งาน cron ชื่อ line-hotspot ตั้งไว้ทุกห้านาที
--   ค่านี้ตั้งไว้ตอนทำแจ้งเหตุเสียชีวิต ซึ่งต้องเร็วจริง
--   แต่จุดที่ชนซ้ำไม่ได้เปลี่ยนทุกห้านาที จึงเป็นการถามบ่อยเกินความจำเป็น
--
-- สอง  ตัวกันส่งซ้ำ ผูกกับตัวเลขในข้อความ
--   line_sent จำว่าเคยส่ง ref ไหนไปแล้ว และ ref ของ hotspot
--   ประกอบด้วยพิกัดกับจำนวนครั้ง ตาย สาหัส เจ็บ ของทุกจุดที่ลงในข้อความ
--   ตัวเลขใดขยับแม้ตัวเดียว ref ก็เป็นค่าใหม่ แปลว่ายังไม่เคยส่ง จึงส่งอีกรอบ
--
-- สาม  ที่ทำให้สองข้อบนกลายเป็นทุกวัน คือรอบข้อมูลเป็นแบบเลื่อน
--   hotspotWindowDays = 30 นับถอยหลังจากเวลาปัจจุบัน ไม่ใช่จากต้นเดือน
--   เหตุที่เกิดเมื่อ 30 วันก่อน จะหลุดออกจากรอบเองเมื่อถึงเวลานั้นของวัน
--   จำนวนครั้งจึงลดลงเองโดยไม่มีใครกรอกอะไรเลย  ref เปลี่ยน  แล้วส่งใหม่
--   นี่คือเหตุผลว่าทำไมข้อความเด้งทั้งที่ไม่มีอุบัติเหตุใหม่
--
-- สาม ข้อนี้คูณกัน  cron ทุกห้านาที จับการขยับได้แทบจะทันทีที่มันขยับ
--
-- ------------------------------------------------------------
-- ที่ไฟล์นี้แก้
-- ------------------------------------------------------------
--
-- ตั้ง cron เป็นสัปดาห์ละครั้ง เช้าวันจันทร์ 09.00 น. เวลาไทย
-- pg_cron อ่านเวลาเป็น UTC จึงเขียน 0 2 เพื่อให้ตรง 09.00 ที่กรุงเทพ
--
-- เพดานจึงกลายเป็นหนึ่งข้อความต่อสัปดาห์ ไม่ว่าตัวเลขจะขยับกี่ครั้งก็ตาม
-- ตัวกันส่งซ้ำยังทำงานเหมือนเดิม ถ้าตัวเลขไม่ขยับเลย สัปดาห์นั้นก็เงียบ

select cron.unschedule(jobname) from cron.job where jobname = 'line-hotspot';

select cron.schedule('line-hotspot', '0 2 * * 1', 'select line_send_hotspots();');

-- ------------------------------------------------------------
-- ถ้าอยากได้ถี่กว่านี้ หรือน้อยกว่านี้ เปลี่ยนแค่บรรทัด schedule ข้างบน
-- ------------------------------------------------------------
--   วันละครั้ง 09.00 น.           '0 2 * * *'
--   สัปดาห์ละครั้ง จันทร์ 09.00   '0 2 * * 1'
--   สองสัปดาห์ครั้ง ทำไม่ได้ตรง ๆ ให้ใช้ '0 2 1,16 * *' คือวันที่ 1 กับ 16
--   เดือนละครั้ง วันที่ 1 09.00   '0 2 1 * *'
--
-- ------------------------------------------------------------
-- ปุ่มลดความถี่อีกสองปุ่ม ถ้าลด cron แล้วยังรู้สึกว่าข้อความรกไป
-- ต้องการลดจำนวนจุดในข้อความ ไม่ใช่จำนวนครั้งที่ส่ง เอาเครื่องหมาย -- ออก
-- ------------------------------------------------------------
--
-- แจ้งเฉพาะจุดที่ชนตั้งแต่ 5 ครั้งขึ้นไป จากเดิม 3
--   update bs_settings set val = to_jsonb(5), updated_at = now()
--    where key = 'hotspotMinPerMonth';
--
-- แจ้งเฉพาะจุดที่มีตายหรือสาหัสตั้งแต่ 3 ราย จากเดิม 2
--   update bs_settings set val = to_jsonb(3), updated_at = now()
--    where key = 'hotspotSevereMinPerMonth';
--
-- ลงในข้อความ 3 จุด จากเดิม 5
--   update bs_settings set val = to_jsonb(3), updated_at = now()
--    where key = 'hotspotTopN';

-- ==========================================================
-- ตรวจผล  คำสั่งสุดท้ายคำสั่งเดียวที่จะแสดงผล
-- ==========================================================

select 'ตารางเวลาใหม่' as รายการ,
       coalesce((select jobname || '  =  ' || schedule
                   from cron.job where jobname = 'line-hotspot'), 'ไม่พบงาน') as ค่า
union all
select 'แปลว่าส่ง',
       case (select schedule from cron.job where jobname = 'line-hotspot')
         when '0 2 * * 1' then 'สัปดาห์ละครั้ง จันทร์ 09.00 น.'
         when '0 2 * * *' then 'วันละครั้ง 09.00 น.'
         when '*/5 * * * *' then 'ทุกห้านาที  ยังไม่ได้แก้'
         else 'ดูตารางข้างบน'
       end
union all
select 'รอบข้อมูล วัน',
       coalesce((select val #>> array[]::text[] from bs_settings
                  where key = 'hotspotWindowDays'), 'ไม่พบ')
union all
select 'เกณฑ์จำนวนครั้ง',
       coalesce((select val #>> array[]::text[] from bs_settings
                  where key = 'hotspotMinPerMonth'), 'ไม่พบ')
union all
select 'เกณฑ์ตายหรือสาหัส ราย',
       coalesce((select val #>> array[]::text[] from bs_settings
                  where key = 'hotspotSevereMinPerMonth'), 'ไม่พบ')
union all
select 'จำนวนจุดต่อข้อความ',
       coalesce((select val #>> array[]::text[] from bs_settings
                  where key = 'hotspotTopN'), 'ไม่พบ')
union all
select 'เคยส่งไปแล้วใน 30 วัน ครั้ง',
       (select count(*)::text from line_sent
         where kind = 'hotspot' and sent_at > now() - interval '30 days')
union all
select 'ส่งครั้งล่าสุด',
       coalesce((select to_char(timezone('Asia/Bangkok', max(sent_at)), 'DD/MM/YYYY HH24:MI')
                   from line_sent where kind = 'hotspot'), 'ยังไม่เคยส่ง');
