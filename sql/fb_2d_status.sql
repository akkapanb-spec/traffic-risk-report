-- รันได้ทุกเมื่อ ไม่เปลี่ยนอะไร ไม่ส่งอะไรออกไป
-- มีไว้ตอบคำถามเดียวคือ ตอนนี้ติดตั้งไปถึงไหนแล้ว
--
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- ค่าที่ควรได้ถ้ารันไฟล์ 1a 1b 1c 2a ครบแล้ว
--   ตารางกันซ้ำ        1
--   ฟังก์ชันสามตัว      3
--   เลขเพจ            147045742304847
--   สวิตช์             false
--   ค่าตั้งค่า          4
--
-- ตั้งใจไม่เรียก fb_token ในไฟล์นี้ เพราะถ้ายังไม่ได้รัน 1b
-- ทั้งคำสั่งจะพังตั้งแต่ตอนแปลคำสั่ง แล้วจะไม่เห็นช่องอื่นเลยสักช่อง
-- ซึ่งขัดกับหน้าที่ของไฟล์นี้ ที่ต้องบอกให้ได้ว่าอะไรขาด
-- อยากรู้ว่าวางโทเคนแล้วหรือยัง ให้ดูจากผลของไฟล์ 1b แทน

select
  (select count(*) from pg_class
    where relname = 'fb_sent')                                              as ตารางกันซ้ำ,
  (select count(*) from pg_proc
    where proname in ('fb_token', 'fb_weekly_text', 'fb_post'))             as ฟังก์ชันสามตัว,
  (select val #>> array[]::text[] from bs_settings where key = 'fbPageId')  as เลขเพจ,
  (select val from bs_settings where key = 'fbEnabled')                     as สวิตช์,
  (select count(*) from bs_settings where key like 'fb%')                   as ค่าตั้งค่า,
  (select count(*) from fb_sent)                                            as เคยยิงไปแล้วกี่ครั้ง;

