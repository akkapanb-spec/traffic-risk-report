-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- รันไฟล์นี้หลังยิงไปแล้วราวสิบวินาที
-- ต้องแยกเป็นคนละไฟล์กับตัวยิง เพราะคำขอออกไปจริงหลังทรานแซกชันปิดเท่านั้น
-- ถ้ายิงกับอ่านอยู่ไฟล์เดียวกัน จะอ่านไม่เจอคำตอบเสมอ
--
-- อ่านรหัสตอบกลับอย่างไร
--   200  สำเร็จ  ในคำตอบจะมีรหัสโพสต์ เอาไปเปิดดูบนเพจได้
--   400  คำขอผิด  มักเป็นเลขเพจผิด หรือเนื้อคำขอผิดรูป
--   190  โทเคนหมดอายุหรือถูกเพิกถอน  ต้องออกโทเคนใหม่
--   200 แต่ไม่มีรหัสโพสต์  ให้อ่านข้อความในคำตอบ มักเป็นเรื่องสิทธิ์
--
-- ถ้ายิงแล้วไม่ผ่าน และอยากลองเรื่องเดิมใหม่
-- ต้องลบแถวที่จองไว้ออกก่อน ไม่งั้นตัวกันโพสต์ซ้ำจะกันไว้ตลอด
-- คำสั่งลบอยู่ท้ายไฟล์ ปิดคำอธิบายไว้ เปิดใช้เมื่อจำเป็น

-- ตัวแก้ไขแสดงผลของคำสั่งสุดท้ายคำสั่งเดียว จึงรวมทุกอย่างไว้ในคำสั่งเดียว
select
  s.kind                                                             as ชนิด,
  s.ref_id                                                           as รหัสอ้างอิง,
  to_char(s.posted_at at time zone 'Asia/Bangkok', 'DD/MM HH24:MI')  as เวลา,
  s.note                                                             as บันทึกของเรา,
  r.status_code                                                      as รหัสตอบกลับ,
  left(r.content, 400)                                               as คำตอบจากเฟซบุ๊ก
from fb_sent s
left join net._http_response r on r.id = s.req_id
order by s.posted_at desc
limit 10;

