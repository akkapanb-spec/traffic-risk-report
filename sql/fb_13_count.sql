-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- ไฟล์นี้เล็กที่สุดเท่าที่จะทำได้ เพราะต้องการคำตอบเดียวและต้องรันผ่านแน่ ๆ
-- ไม่แตะตารางของระบบ ไม่ต่อตารางไหนเข้าด้วยกัน จึงไม่มีอะไรให้พังได้
--
-- อ่านผลอย่างไร
--   แถวทั้งหมด เป็น 0        สมุดว่างจริง ตัวส่งไม่เคยจองที่สำเร็จเลยสักครั้ง
--   แถวทั้งหมด มากกว่า 0     สมุดไม่ว่าง แปลว่าไฟล์ 2b ที่ไม่แสดงอะไร เป็นเรื่องการแสดงผล
--                            ไม่ใช่เรื่องข้อมูล แล้วต้องไปดูที่บันทึกของตัวตั้งเวลาแทน
--   ประกาศ เป็น 0            ไฟล์ 9 ที่รันเมื่อวานไม่ได้เข้า ซึ่งอธิบายได้หลายอย่าง

select
  (select count(*) from fb_sent)                         as แถวทั้งหมด,
  (select count(*) from fb_sent where kind = 'advisory') as ประกาศ,
  (select count(*) from fb_sent where kind = 'death')    as เสียชีวิต,
  (select count(*) from fb_sent where kind = 'weekly')   as รายสัปดาห์,
  (select count(*) from fb_sent where kind = 'hotspot')  as จุดซ้ำ,
  (select to_char(max(posted_at) at time zone 'Asia/Bangkok', 'DD/MM HH24:MI')
     from fb_sent)                                       as จดล่าสุดเมื่อ,
  (select val #>> array[]::text[] from bs_settings where key = 'fbEnabled') as สวิตช์;

