-- ============================================================
-- ค้นรหัสกลุ่มไลน์จากบันทึกข้อความเข้า
-- ============================================================
-- ไฟล์นี้ "อ่านอย่างเดียว" ไม่สร้าง ไม่แก้ ไม่ลบ ไม่ส่งอะไรเข้าไลน์
-- ไม่ต้องใช้ token ไม่ต้องแก้อะไรก่อนรัน มีคำสั่งเดียว
--
-- ตรวจก่อนกด Run: บรรทัดแรกของช่อง editor ต้องเป็นเส้น ==== ชุดนี้
-- ถ้ามี $0 ค้างอยู่บรรทัดสุดท้าย ให้ลบทิ้งก่อนกด Run
-- ไฟล์นี้ไม่มีวงเล็บปีกกาเลยแม้แต่ตัวเดียว
--
-- วิธีที่ใช้ค้น
--   แปลงทั้งแถวเป็นข้อความก้อนเดียวแล้วค้นในนั้น
--   จึงไม่ต้องรู้ชื่อคอลัมน์ล่วงหน้า และไม่พังถ้าโครงตารางไม่ตรงกับที่เดาไว้
--
-- อ่านผลยังไง
--   หมวด 3 คือคำตอบ ถ้ามีรหัสขึ้นต้นด้วย C ตามด้วยอักษรและตัวเลขยาว ๆ
--   ให้คัดลอกมาส่งให้ผม จะเขียนคำสั่งลงทะเบียนกลุ่มให้
--
--   หมวด 2 เป็น 0 แปลว่าไม่เคยมีข้อความจากกลุ่มเข้ามาเลย
--   ต้องเปิดช่องรับข้อความแล้วให้ใครสักคนพิมพ์ในกลุ่มหนึ่งครั้ง
--
--   หมวด 4 เป็นข้อความดิบไว้ดูเผื่อรูปแบบรหัสไม่ตรงกับที่ค้น
-- ============================================================

select '1 บันทึกทั้งหมด' as หมวด, count(*)::text as รายละเอียด
  from line_hook_log

union all
select '2 บันทึกที่มาจากกลุ่ม', count(*)::text
  from line_hook_log l
 where to_jsonb(l)::text like '%groupId%'

union all
select distinct '3 รหัสกลุ่มที่พบ',
       coalesce(substring(to_jsonb(l)::text from 'C[0-9a-fA-F]+'), 'อ่านรูปแบบไม่ออก')
  from line_hook_log l
 where to_jsonb(l)::text like '%groupId%'

union all
(select '4 ตัวอย่างข้อความดิบ',
        substr(to_jsonb(l)::text, greatest(position('groupId' in to_jsonb(l)::text) - 20, 1), 120)
   from line_hook_log l
  where to_jsonb(l)::text like '%groupId%'
  limit 3)

union all
(select '5 บันทึกล่าสุดโดยไม่กรอง', substr(to_jsonb(l)::text, 1, 150)
   from line_hook_log l
  limit 3)

order by 1, 2;

-- ============================================================
-- ถ้าหมวด 2 เป็น 0 ต้องเก็บรหัสกลุ่มใหม่ ทำตามนี้
-- ============================================================
-- 1 เข้า LINE Developers Console เลือกช่องแชทของบอทตัวนี้
-- 2 แท็บ Messaging API ดูหัวข้อ Webhook settings
--     ถ้า Webhook URL ว่าง หรือ Use webhook ปิดอยู่ ให้บอกผม จะช่วยดูให้
--     ถ้ามีที่อยู่และเปิดอยู่แล้ว ข้ามไปข้อ 3 ได้เลย
-- 3 พิมพ์อะไรก็ได้ในกลุ่มหนึ่งข้อความ เช่นคำว่า ทดสอบ
-- 4 รันไฟล์นี้ใหม่อีกครั้ง รหัสกลุ่มจะโผล่ในหมวด 3
--
-- การเปิดช่องรับข้อความไม่ได้ทำให้บอทกลับมาตอบคำถามอัตโนมัติ
-- คำสั่งอัตโนมัติที่เคยสั่งปิดไว้ ยังปิดอยู่ตามเดิม เป็นคนละสวิตช์กัน
-- ============================================================
