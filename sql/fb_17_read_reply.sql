-- อ่านคำตอบที่เฟซบุ๊กส่งกลับมา  อ่านอย่างเดียว ไม่ส่งอะไรออกไป
-- ============================================================
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- ------------------------------------------------------------
-- sent เป็น 1 ยังไม่ได้แปลว่าโพสต์ขึ้นแล้ว
-- ------------------------------------------------------------
-- pg_net ยิงคำขอแล้วไม่รอคำตอบ  ฟังก์ชันจึงคืน sent เป็น 1 ทันทีที่ยิงออกไป
-- ต่อให้เฟซบุ๊กตอบกลับมาว่าโทเคนหมดอายุ ค่าที่เห็นก็ยังเป็น 1 อยู่ดี
-- คำตอบจริงไปโผล่อีกตารางหนึ่ง ซึ่งไฟล์นี้อ่าน
--
-- ถ้าไฟล์นี้ขึ้นแดงว่าไม่มีสิทธิ์อ่านตาราง ก็เป็นคำตอบเหมือนกัน
-- แปลว่าฝั่งฐานข้อมูลตรวจสอบไม่ได้ ต้องดูที่หน้าเพจอย่างเดียว
--
-- ------------------------------------------------------------
-- อ่านรหัสตอบกลับอย่างไร
-- ------------------------------------------------------------
--   200  สำเร็จ  ในคำตอบจะมีรหัสโพสต์ เอาไปเปิดดูบนเพจได้
--   190  โทเคนหมดอายุหรือถูกเพิกถอน  ต้องออกโทเคนใหม่
--   400  คำขอผิดรูป มักเป็นเลขเพจผิด
--   100 พร้อมข้อความเรื่องรูป  เฟซบุ๊กดึงภาพจากลิงก์ไม่ได้
--        กรณีนี้ทั้งโพสต์จะไม่ขึ้น ไม่ใช่ขึ้นแบบไม่มีภาพ

select
  r.id                                                          as เลขคำขอ,
  to_char(r.created at time zone 'Asia/Bangkok', 'DD/MM HH24:MI:SS') as เวลาที่ตอบกลับ,
  r.status_code                                                 as รหัสตอบกลับ,
  left(coalesce(r.content, r.error_msg, ''), 300)               as คำตอบ
from net._http_response r
order by r.id desc
limit 5;

