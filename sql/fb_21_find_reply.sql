-- ============================================================
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- ------------------------------------------------------------
-- ทำไมไฟล์ 17 ถึงไม่เจอ
-- ------------------------------------------------------------
-- ไฟล์ 17 เอาห้าแถวล่าสุดมาดูเฉย ๆ
-- แต่ตารางนี้เป็นที่รวมคำตอบของทุกอย่างในระบบ ไม่ใช่ของเฟซบุ๊กอย่างเดียว
-- งานตรวจสิทธิ์กิจกรรมแจกหมวกวิ่งทุกนาที และยิงทีละหลายคำขอ
-- ห้าแถวล่าสุดจึงเป็นของงานนั้นทั้งหมด คำตอบของเฟซบุ๊กจมอยู่ข้างล่าง
--
-- ตารางนี้ไม่ได้เก็บที่อยู่ปลายทางไว้ จึงกรองด้วยที่อยู่ไม่ได้
-- ต้องกรองจากเนื้อคำตอบแทน คำตอบของ Graph จะมีคำเฉพาะของมันอยู่

select
  r.id                                                               as เลขคำขอ,
  to_char(r.created at time zone 'Asia/Bangkok', 'DD/MM HH24:MI:SS') as เวลาที่ตอบกลับ,
  r.status_code                                                      as รหัสตอบกลับ,
  left(coalesce(r.content, r.error_msg, ''), 400)                    as คำตอบ
from net._http_response r
where coalesce(r.content, '') like '%is_published%'
   or coalesce(r.content, '') like '%permalink_url%'
   or coalesce(r.content, '') like '%post_id%'
   or coalesce(r.content, '') like '%graph%'
   or coalesce(r.content, '') like '%OAuthException%'
   or coalesce(r.error_msg, '') <> ''
order by r.id desc
limit 10;

