--   2 แตกลงตารางผู้เสียชีวิตหรือยัง
--   3 ช่องระบุสถานที่เสียชีวิตถูกเติมว่า เสียชีวิตที่เกิดเหตุ หรือไม่
--     ถ้าช่องนี้ว่างหรือเป็นค่าอื่น ระบบจะข้ามไม่แจ้ง ตามที่กำหนดไว้
--   4 รายนี้ค้างรอส่งอยู่หรือถูกส่งไปแล้ว
--   5 ปลายทางเปิดรับอยู่ไหม ถ้าปิดอยู่จะยังไม่ส่งจนกว่าจะเปิด
-- ============================================================

-- สาขาที่มี order by หรือ limit ต้องมีวงเล็บครอบเสมอเมื่ออยู่ใน union all
(select '1 เคสอุบัติเหตุล่าสุด' as ลำดับ,
        a.accident_code || ' · ' ||
        to_char(timezone('Asia/Bangkok', a.incident_datetime), 'DD/MM HH24:MI') || ' · ' ||
        coalesce(a.place, 'ไม่ระบุสถานที่') as รายละเอียด
   from accidents a
  where a.recorded_at > now() - interval '6 hours'
  order by a.recorded_at desc
  limit 3)

union all
select '2 ผู้เสียชีวิตที่เพิ่งแตกออกมา',
       'รหัส ' || d.id::text || ' · ' ||
       coalesce(d.gender, 'ไม่ระบุเพศ') || ' · อายุ ' || coalesce(d.age::text, 'ไม่ระบุ') ||
       ' · ' || coalesce(d.road_name, 'ไม่ระบุถนน')
  from deaths d
 where d.incident_datetime > now() - interval '6 hours'

union all
select '3 ช่องระบุสถานที่เสียชีวิต',
       'รหัส ' || d.id::text || ' · ' ||
       case when btrim(coalesce(d.col_g, '')) = 'เสียชีวิตที่เกิดเหตุ'
            then 'เสียชีวิตที่เกิดเหตุ · เข้าเกณฑ์แจ้งเตือน'
            else coalesce(nullif(btrim(d.col_g), ''), 'ว่าง') || ' · ไม่เข้าเกณฑ์ ระบบจะข้าม' end
  from deaths d
 where d.incident_datetime > now() - interval '6 hours'

union all
select '4 สถานะการส่ง',
       'รหัส ' || d.id::text || ' · ' ||
       case when exists (select 1 from line_sent s
                          where s.kind = 'death' and s.ref_id = d.id::text)
            then 'มีบันทึกแล้ว จะไม่ส่งซ้ำ'
            else 'ค้างรอส่ง จะส่งรอบถัดไปถ้าปลายทางเปิด' end
  from deaths d
 where d.incident_datetime > now() - interval '6 hours'

union all
select '5 ปลายทาง',
       t.target_type || ' · ' || coalesce(t.label, 'ไม่มีชื่อ') || ' · ' ||
       case when t.enabled then 'เปิด' else 'ปิดอยู่ จึงยังไม่ส่ง' end
  from line_targets t

order by 1, 2;

