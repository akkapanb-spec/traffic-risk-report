insert into line_sent (kind, ref_id, target_id, ok, detail)
select 'death', d.id::text, 'SKIP', true, 'ข้อมูลเก่าก่อนซ่อมระบบ 17 ส.ค. 69'
  from deaths d
 where d.incident_datetime < now() - interval '1 day'
   and not exists (
     select 1 from line_sent s where s.kind = 'death' and s.ref_id = d.id::text)
on conflict do nothing;

