-- ============================================================
-- เปิดดูโค้ดจริงของฟังก์ชันตรวจสิทธิ์
-- ============================================================
-- ไฟล์นี้ "อ่านอย่างเดียว" ไม่สร้าง ไม่แก้ ไม่ลบ ไม่เพิ่มอะไรเลย
-- ไม่ต้องใช้ token ไม่ต้องแก้อะไรก่อนรัน
-- มีคำสั่งเดียว ผลจะออกครบในตารางเดียว
--
-- ตรวจก่อนกด Run: บรรทัดแรกของช่อง editor ต้องเป็นเส้น ==== ชุดนี้
-- ถ้ามี $0 ค้างอยู่บรรทัดสุดท้าย ให้ลบทิ้งก่อนกด Run
--
-- ทำไมต้องดูตัวนี้
--   ทุกอย่างที่ตรวจมาสะอาดหมด ทั้งข้อมูลที่ส่ง เครือข่าย เบราว์เซอร์ ตาราง
--   และผมเพิ่งยิงข้อมูลไทยขนาดเท่าของจริงเข้าไป ก็ผ่านฉลุย
--
--   ความต่างเดียวที่เหลือคือ การยิงของผมใช้ token ปลอม
--   ฟังก์ชันจึงคืนค่าออกไปตั้งแต่ด่านแรก ไม่เคยเข้าไปทำงานส่วนที่เหลือเลย
--   ส่วนของคุณมีสิทธิ์จริง มันจึงเดินต่อเข้าไปในส่วนที่ผมยิงไม่ถึง
--
--   ด่านตรวจสิทธิ์คือจุดแรกที่ทำงานต่างกันระหว่างสองกรณีนี้
--   ถ้าโค้ดตรงนั้นมีการเอาข้อความไปใส่ตัวแปรชนิด json จะพังแบบที่เห็นพอดี
--   ซึ่งเป็นรูปแบบที่การค้นหาครั้งก่อนของผมมองไม่เห็น เพราะไม่มีคำว่า ::json
-- ============================================================

select f.proname as ฟังก์ชัน,
       t.ln      as บรรทัดที่,
       t.txt     as โค้ด
  from pg_proc f
  join pg_namespace n on n.oid = f.pronamespace
 cross join lateral unnest(string_to_array(f.prosrc, chr(10)))
       with ordinality as t(txt, ln)
 where n.nspname = 'public'
   and f.proname in ('officer_session_user', 'admin_check_')
 order by f.proname, t.ln;

