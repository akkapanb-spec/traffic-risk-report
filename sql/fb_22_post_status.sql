-- ============================================================
-- แยกคำตอบของเฟซบุ๊กออกเป็นช่อง ๆ  อ่านอย่างเดียว
-- ============================================================
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- คำตอบมาแล้วเมื่อ 08:23:44 รหัส 200 แต่ตัวแก้ไขตัดข้อความให้สั้น
-- จึงเห็นแค่สองช่องแรก ยังไม่เห็นช่องที่ต้องการ
-- ไฟล์นี้แกะคำตอบออกเป็นช่องแยก จะได้อ่านได้ครบโดยไม่ถูกตัด
--
-- อ่านผลอย่างไร
--   เผยแพร่แล้ว เป็น true และ ใครเห็นได้ เป็น EVERYONE
--     โพสต์ปกติทุกอย่าง ที่ไม่เห็นบนวอลล์เป็นเรื่องการแสดงผลฝั่งเฟซบุ๊ก
--   เผยแพร่แล้ว เป็น false
--     เจอต้นเหตุ ต้องบอกเฟซบุ๊กตอนสร้างว่าให้เผยแพร่ด้วย
--   ชนิดเรื่องราว เป็น added_photos
--     เป็นเรื่องราวแบบเพิ่มรูป ซึ่งบางครั้งเฟซบุ๊กจัดให้อยู่ในแท็บรูปภาพ

select
  to_char(r.created at time zone 'Asia/Bangkok', 'DD/MM HH24:MI:SS')  as เวลาที่ตอบกลับ,
  (r.content::jsonb) ->> 'is_published'                               as เผยแพร่แล้ว,
  (r.content::jsonb) -> 'privacy' ->> 'value'                         as ใครเห็นได้,
  (r.content::jsonb) ->> 'status_type'                                as ชนิดเรื่องราว,
  (r.content::jsonb) ->> 'created_time'                               as เวลาที่สร้าง,
  (r.content::jsonb) ->> 'permalink_url'                              as ที่อยู่ของโพสต์
from net._http_response r
where coalesce(r.content, '') like '%is_published%'
order by r.id desc
limit 5;

