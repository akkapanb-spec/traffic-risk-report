-- ไม่แจ้งประกาศที่มีอยู่ก่อนติดตั้ง  แจ้งเฉพาะประกาศที่เริ่มหลังจากนี้
-- ถ้ามีอักขระแปลกปลอมต่อท้ายบรรทัดสุดท้าย ให้ลบออกก่อนกด Run
-- รันก่อน 06:00 ของวันที่ 12 ก.ย. 2569 ไม่งั้นข้อความรอบแรกจะออกไปก่อน
--
-- ------------------------------------------------------------
-- เหตุผล
-- ------------------------------------------------------------
-- line_advisory_1.sql จะแจ้งทุกประกาศที่ยังมีผลอยู่และบอทยังไม่เคยแจ้ง
-- ตอนติดตั้งมีสองรายการที่ยังมีผล คือ #9 และ #15
-- ทั้งสองรายการแจ้งในกลุ่มไปแล้วตั้งแต่ตอนลงประกาศ ผู้ใช้ยืนยันเมื่อ 11 ก.ย.
-- ถ้าปล่อยไว้ 06:03 บอทจะแจ้งซ้ำ ซึ่งคนในกลุ่มจะอ่านเป็นเรื่องใหม่
--
-- ไฟล์นี้จดว่าทุกประกาศที่เริ่มไปแล้ว ถือว่าแจ้งแล้ว
-- ประกาศที่เริ่มหลังจากนี้ บอทจะแจ้งตามปกติ
--
-- จดรวมประกาศเก่าที่หมดเวลาแล้วด้วย
-- เผื่อวันหลังเจ้าหน้าที่ไปขยายเวลาประกาศเก่า มันจะได้ไม่โผล่เป็นเรื่องใหม่
--
-- รันซ้ำได้ ไม่เกิดอะไรขึ้นกับรายการที่จดไว้แล้ว

insert into line_adv_announced (adv_id, ref)
select id, 'backlog'
from traffic_advisories
where starts_at <= now()
on conflict (adv_id) do nothing;

-- ==========================================================
-- ตรวจผล  คำสั่งสุดท้ายคำสั่งเดียวที่จะแสดงผล
-- ==========================================================

select 'จดว่าแจ้งแล้วทั้งหมด' as รายการ,
  (select count(*)::text || ' รายการ' from line_adv_announced) as ผล
union all
select 'ในนั้นที่ยังมีผลอยู่ตอนนี้',
  coalesce((select string_agg('#' || a.id || ' ' || a.title, '  /  ' order by a.starts_at)
            from traffic_advisories a join line_adv_announced x on x.adv_id = a.id
            where a.ends_at > now() and a.closed_at is null), 'ไม่มี')
union all
select 'ประกาศที่ยังรอแจ้ง',
  coalesce((select string_agg('#' || id || ' ' || title, '  /  ' order by starts_at)
            from traffic_advisories a
            where a.ends_at > now() and a.closed_at is null
              and not exists (select 1 from line_adv_announced x where x.adv_id = a.id)),
           'ไม่มี  06:03 จะไม่ส่งอะไร')
union all
select 'ขั้นต่อไป', 'ประกาศที่เจ้าหน้าที่ลงใหม่หลังจากนี้ จะเข้ากลุ่มภายใน 5 นาทีหลังถึงเวลาเริ่ม';
