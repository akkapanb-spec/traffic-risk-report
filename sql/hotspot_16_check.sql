-- ตัวคำนวณจุดซ้ำถูกเขียนใหม่มาสี่รอบกว่าจะนิ่ง ถ้าของจริงในฐานข้อมูล
-- ต่างจากไฟล์ในโปรเจกต์แม้แต่บรรทัดเดียว แล้วผมเขียนทับจากไฟล์
-- การแก้ครั้งนั้นจะหายไปเงียบ ๆ และจะรู้ตัวอีกทีตอนข้อความที่ส่งออกไปผิด
-- เคยเกิดมาแล้วกับตัวคำนวณความหนาแน่น จึงไม่เดาอีก
--
-- อ่านผลอย่างไร
--   ตรงกัน        แก้ต่อได้เลย ผมจะเพิ่มรายการจุดพร้อมพิกัดให้
--   ไม่ตรงกัน      อย่าเพิ่งแก้ ส่งผลมาให้ผมดูก่อน แล้วผมจะดึงของจริงมาต่อยอดแทน
--   ไม่พบฟังก์ชัน   ยังไม่เคยรันไฟล์ line_pub_3_hotspot.sql
--
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์

select
  case
    when p.prosrc is null then 'ไม่พบฟังก์ชัน'
    when md5(p.prosrc) in ('e9cb9fc66942ebbc0d968abf3101be02',
                           '45fd143f11ea2cbc8a9f9beeb5966abb') then 'ตรงกัน แก้ต่อได้'
    else 'ไม่ตรงกัน อย่าเพิ่งแก้'
  end                                                    as ผลการเช็ก,
  coalesce(length(p.prosrc), 0)                          as ความยาวของจริง,
  10617                                                  as ความยาวในไฟล์,
  coalesce(md5(p.prosrc), '')                            as ลายนิ้วมือของจริง,
  (select count(*) from pg_proc where proname = 'line_hotspot_build') as จำนวนฟังก์ชันชื่อนี้
from (select prosrc from pg_proc where proname = 'line_hotspot_build' limit 1) p
right join (select 1) one on true;

