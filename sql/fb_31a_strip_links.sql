-- ==========================================================
-- 2  ตัวแยกลิงก์
-- ==========================================================

create or replace function fb_strip_links(p_text text)
returns jsonb
language plpgsql
immutable
as $fn$
declare
  v_body  text;
  v_links text;
begin
  if coalesce(p_text, '') = '' then
    return jsonb_build_object('text', '', 'links', '');
  end if;

  select
    string_agg(t.line, chr(10) order by t.ord)
      filter (where position('http' in t.line) = 0
                and btrim(t.line) <> 'ดูรูปภาพและรายละเอียดทั้งหมด'
                and btrim(t.line) <> 'ดูจุดเสี่ยงและสถิติทั้งหมดได้ที่'
                and btrim(t.line) <> 'รายละเอียดที่นี่'),
    string_agg(btrim(t.line), chr(10) order by t.ord)
      filter (where position('http' in t.line) > 0)
  into v_body, v_links
  from unnest(string_to_array(p_text, chr(10))) with ordinality as t(line, ord);

  v_body := coalesce(v_body, '');

  -- บรรทัดว่างที่เหลือจากการตัด ยุบให้เหลือเว้นบรรทัดเดียว
  -- ทำสามรอบ เผื่อกรณีที่ลิงก์หลายบรรทัดติดกันถูกตัดพร้อมกัน
  v_body := replace(v_body, chr(10) || chr(10) || chr(10), chr(10) || chr(10));
  v_body := replace(v_body, chr(10) || chr(10) || chr(10), chr(10) || chr(10));
  v_body := replace(v_body, chr(10) || chr(10) || chr(10), chr(10) || chr(10));

  return jsonb_build_object('text', btrim(v_body), 'links', btrim(coalesce(v_links, '')));
end;
$fn$;

revoke execute on function fb_strip_links(text) from public, anon, authenticated;

-- ==========================================================
-- 3  ตรวจ  ดูของจริงว่าตัดแล้วเหลืออะไร
-- ==========================================================
-- ช่อง ตัวโพสต์ ต้องไม่มีคำว่า http เหลืออยู่เลย
-- ช่อง ลิงก์ที่จะไปอยู่ในคอมเมนต์ ต้องมีลิงก์ครบตามที่เคยมีในตัวโพสต์

select
  left(fb_strip_links(line_adv_item_text(t.id)) ->> 'text', 400)  as ตัวโพสต์,
  fb_strip_links(line_adv_item_text(t.id)) ->> 'links'            as ลิงก์ที่จะไปอยู่ในคอมเมนต์
from traffic_advisories t
where t.closed_at is null
order by t.id desc
limit 2;

