-- รันเรียงตามลำดับ 1a 1b 1c  ห้ามข้าม
-- ไฟล์ละหนึ่งฟังก์ชัน จะได้รู้ทันทีว่าพังไฟล์ไหน
--
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- โทเคนไม่ได้อยู่ในไฟล์นี้ และต้องไม่อยู่ในไฟล์ไหนของโปรเจกต์นี้เลย
-- เก็บไว้ในตู้นิรภัยของ Supabase ใช้ชื่อ fb_page_access_token
-- ทำแบบเดียวกับโทเคนไลน์ที่ใช้อยู่ ซึ่งอยู่ในตู้เดียวกันชื่อ line_channel_access_token
--
-- วิธีใส่โทเคน  หน้า Supabase เมนู Project Settings แล้วไปที่ Vault
-- กด New secret ตั้งชื่อให้ตรงกับที่เขียนไว้ข้างล่างนี้ แล้ววางค่าลงไป
-- วางแล้วไม่มีใครอ่านค่ากลับออกมาได้ รวมทั้งตัวผมเองด้วย
--
-- บรรทัดถอนสิทธิ์ท้ายไฟล์สำคัญมาก ห้ามตัดออก
-- ถ้าไม่ถอน หน้าเว็บสาธารณะจะเรียกฟังก์ชันนี้แล้วได้โทเคนไปตรง ๆ

create or replace function fb_token()
returns text
language sql
stable
security definer
set search_path = public, extensions, vault
as $fn$
  select decrypted_secret from vault.decrypted_secrets where name = 'fb_page_access_token';
$fn$;

revoke execute on function fb_token() from public, anon, authenticated;

-- ตรวจ  ต้องได้ฟังก์ชัน 1
-- ช่องใส่โทเคนแล้วหรือยัง จะเป็นจริงก็ต่อเมื่อวางโทเคนในตู้นิรภัยเรียบร้อยแล้ว
-- ตั้งใจไม่แสดงตัวโทเคน แสดงแค่ว่ามีหรือไม่มี
select
  (select count(*) from pg_proc where proname = 'fb_token') as ฟังก์ชัน,
  (fb_token() is not null)                                  as ใส่โทเคนแล้วหรือยัง;

-- จบไฟล์  อย่าเคาะบรรทัดใหม่ต่อท้ายบรรทัดนี้ ->