-- ความจริงคือเราเลิกรอคำตอบ ไม่ใช่เฟซบุ๊กไม่ได้รับคำขอ
-- คำขอไปถึงและถูกสร้างเป็นโพสต์เรียบร้อยตั้งแต่ครั้งแรกแล้ว
-- เราแค่ไม่เห็นคำตอบ จึงเข้าใจว่าไม่สำเร็จ
--
