-- กฎที่ไฟล์นี้บังคับไว้
-- ------------------------------------------------------------
-- แถวที่มีเลขคำขออยู่แล้ว แปลว่าเคยยิงออกไปจริง  ห้ามลบเพื่อยิงใหม่
-- ไม่ว่าคำตอบจะเป็นอะไรหรือจะไม่มีคำตอบเลยก็ตาม
-- ต้องไปเปิดหน้าเพจดูด้วยตาก่อนเสมอ ว่ามีโพสต์อยู่แล้วหรือยัง
--
-- แถวที่ยังไม่มีเลขคำขอ ลบได้ปลอดภัย เพราะไม่เคยมีอะไรออกไป

create or replace function fb_clear_for_retry(p_kind text, p_ref text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_req bigint;
  v_has boolean;
begin
  select req_id, true into v_req, v_has
    from fb_sent where kind = p_kind and ref_id = p_ref;

  if not coalesce(v_has, false) then
    return jsonb_build_object('success', true, 'cleared', false,
      'message', 'ไม่มีแถวนี้อยู่แล้ว ยิงใหม่ได้เลย');
  end if;

  if v_req is not null then
    return jsonb_build_object('success', false, 'cleared', false, 'request_id', v_req,
      'message', 'แถวนี้เคยยิงออกไปแล้ว ห้ามลบเพื่อยิงซ้ำ  '
              || 'ไปเปิดหน้าเพจดูก่อนว่ามีโพสต์นี้อยู่หรือยัง  '
              || 'หมดเวลารอไม่ได้แปลว่าไม่ได้โพสต์');
  end if;

  delete from fb_sent where kind = p_kind and ref_id = p_ref;
  return jsonb_build_object('success', true, 'cleared', true,
    'message', 'ลบแล้ว แถวนี้ไม่เคยยิงออกไป ยิงใหม่ได้');
end;
$fn$;

revoke execute on function fb_clear_for_retry(text, text) from public, anon, authenticated;

-- ตรวจ  ลองสั่งล้างแถวของสัปดาห์นี้ ต้องถูกปฏิเสธ เพราะยิงไปแล้วจริง
select fb_clear_for_retry('weekly',
  to_char(now() at time zone 'Asia/Bangkok', 'IYYY') || '-' ||
  to_char(now() at time zone 'Asia/Bangkok', 'IW') || '-7') as ผลการลองล้าง;

