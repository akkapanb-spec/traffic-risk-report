-- หนึ่ง  ตัดคำว่า ถนน หรือ ถ. ที่นำหน้าออก
-- สอง   ตัดส่วนหลังขีดทับออก เช่น ในเขตเทศบาลนคร กับ นอกเขตเทศบาล
--       สำหรับการ์ดสาธารณะ ถนนสายเดียวกันควรเป็นแถวเดียว
-- สาม   บีบช่องว่างซ้อนให้เหลือช่องเดียว
--
-- ที่กฎนี้ทำไม่ได้ คือ ทล.1 กับ พหลโยธิน เป็นสายเดียวกันแต่เขียนคนละระบบ
-- อันนั้นต้องมีตารางจับคู่ ซึ่งยังไม่ทำตอนนี้
-- ท้ายไฟล์มีบรรทัดตรวจให้ดูว่าอะไรรวมกับอะไรบ้าง ถ้ามีคู่แบบนั้นจะเห็นเอง

-- ==========================================================
-- 1  ชื่อกลางที่ใช้จัดกลุ่ม
-- ==========================================================

create or replace function fb_road_key(p_road text)
returns text
language plpgsql
immutable
as $fn$
declare
  v text;
begin
  v := btrim(coalesce(p_road, ''));
  if v = '' then
    return '';
  end if;

  -- ตัดส่วนหลังขีดทับ
  v := btrim(split_part(v, '/', 1));

  -- บีบช่องว่างซ้อน  ใช้ชุดอักขระแบบ POSIX จะได้ไม่ต้องมีแบ็กสแลชในไฟล์
  v := btrim(regexp_replace(v, '[[:space:]]+', ' ', 'g'));

  -- ตัดคำนำหน้า
  if left(v, 3) = 'ถนน' then
    v := btrim(substr(v, 4));
  elsif left(v, 2) = 'ถ.' then
    v := btrim(substr(v, 3));
  end if;

  return v;
end;
$fn$;

-- ==========================================================
-- 2  ชื่อที่จะพิมพ์ลงการ์ด
-- ==========================================================
-- เติมคำว่า ถนน กลับเข้าไปให้อ่านลื่น แต่ไม่เติมให้ชื่อที่เป็นรหัสทางหลวง
-- เพราะ ถนนทล.1 ไม่มีใครเขียนกัน

create or replace function fb_road_label(p_key text)
returns text
language plpgsql
immutable
as $fn$
declare
  v text;
begin
  v := btrim(coalesce(p_key, ''));
  if v = '' then
    return 'ไม่ระบุถนน';
  end if;

  if left(v, 2) in ('ทล', 'นว') or left(v, 3) = 'อปท' then
    return v;
  end if;

  return 'ถนน' || v;
end;
$fn$;

grant execute on function fb_road_key(text)   to anon, authenticated;
grant execute on function fb_road_label(text) to anon, authenticated;

-- ==========================================================
-- 3  ตรวจ  ดูว่าอะไรถูกรวมเข้ากับอะไร
-- ==========================================================
-- คอลัมน์สุดท้ายคือชื่อดิบทุกแบบที่ถูกรวมมาไว้ด้วยกัน
-- ถ้าเห็นชื่อที่ไม่ควรอยู่ด้วยกัน ให้ส่งกลับมาก่อน อย่าเพิ่งรัน 7b 7c

select
  fb_road_label(fb_road_key(a.road))              as ชื่อที่จะขึ้นการ์ด,
  count(*)                                        as จำนวนครั้ง,
  count(distinct btrim(coalesce(a.road, '')))     as รวมมาจากกี่แบบ,
  string_agg(distinct btrim(coalesce(a.road, '')), '  ·  ') as ชื่อดิบที่รวมมา
from accidents a
where coalesce(btrim(a.road), '') <> ''
group by 1
order by 2 desc
limit 25;

