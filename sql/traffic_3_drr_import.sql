-- ============================================================
-- อ่านรายการอ้างอิง
-- ============================================================
create or replace function tv_drr_list(p_token text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err jsonb;
begin
  v_err := admin_check_(p_token);
  if v_err is not null then return v_err; end if;

  return jsonb_build_object('success', true,
    'rows', coalesce((select jsonb_agg(jsonb_build_object(
        'road_code', d.road_code, 'road_name', d.road_name, 'year', d.year,
        'mc', d.mc, 'sum_aadt', d.sum_aadt, 'source', d.source,
        -- ถ้ามีถนนในโครงข่ายที่รหัสตรงกัน บอกไว้เลย จะได้กดใช้ค่าได้ทันที
        'road_id', (select r.id from rn_roads r
                    where rn_road_norm(r.code) = rn_road_norm(d.road_code) limit 1))
      order by d.sum_aadt desc)
      from tv_drr_volume d), '[]'::jsonb));
end $$;

-- ============================================================
-- เอาค่าจากตารางอ้างอิงไปใช้กับถนนในโครงข่าย
-- ============================================================
-- ไม่ทำอัตโนมัติ เพราะสายทางของกรมทางหลวงชนบทกับถนนที่เจ้าหน้าที่วาด
-- ไม่ได้ตรงกันเป็นหนึ่งต่อหนึ่ง ต้องให้คนตัดสินใจว่าอันไหนคืออันเดียวกัน
create or replace function tv_use_drr(p_token text, p_road_code text, p_road_id bigint)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err jsonb; d tv_drr_volume%rowtype;
begin
  v_err := admin_check_(p_token);
  if v_err is not null then return v_err; end if;

  select * into d from tv_drr_volume where road_code = p_road_code;
  if not found then return jsonb_build_object('success', false, 'message', 'ไม่พบสายทางนี้ในตารางอ้างอิง'); end if;
  if not exists (select 1 from rn_roads where id = p_road_id) then
    return jsonb_build_object('success', false, 'message', 'ไม่พบถนนสายนี้ในโครงข่าย');
  end if;

  insert into rn_traffic_volume (road_id, year, aadt, source, note)
  values (p_road_id, d.year, d.sum_aadt, d.source, 'นำมาจากสายทาง ' || d.road_code || ' ' || d.road_name)
  on conflict (road_id, year, km_from, km_to) do update set
    aadt = excluded.aadt, source = excluded.source, note = excluded.note, updated_at = now();

  return jsonb_build_object('success', true,
    'message', 'ใช้ค่า ' || d.sum_aadt || ' คัน/วัน จาก ' || d.road_code || ' แล้ว');
end $$;

grant execute on function tv_drr_list(text)                   to anon, authenticated;
grant execute on function tv_use_drr(text, text, bigint)      to anon, authenticated;

