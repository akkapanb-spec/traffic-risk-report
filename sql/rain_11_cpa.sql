insert into bs_settings (key, val) values ('rainRingKm', to_jsonb(8))
on conflict (key) do nothing;

-- ==========================================================
-- 2  สูตรใหม่
-- ==========================================================
-- ชื่อและชุดพารามิเตอร์เหมือนเดิมทุกอย่าง จึงเขียนทับได้ ไม่ต้องลบก่อน
-- ผู้เรียกเดิมไม่ต้องแก้ และคีย์เดิมที่เคยคืนมาก็ยังคืนเหมือนเดิม
-- เพิ่มคีย์ใหม่เข้าไป ไม่ได้เอาของเก่าออก

create or replace function rain_eta(p_row rain_track)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  v_ring  numeric := coalesce((select (val #>> array[]::text[])::numeric
                               from bs_settings where key = 'rainRingKm'), 8);
  v_re    numeric;   -- ตำแหน่งฝน ตะวันออก
  v_rn    numeric;   -- ตำแหน่งฝน เหนือ
  v_ve    numeric;   -- ความเร็ว ตะวันออก
  v_vn    numeric;   -- ความเร็ว เหนือ
  v_dist  numeric;
  v_speed numeric;
  v_dot   numeric;
  v_tcpa  numeric;   -- ชั่วโมง จนถึงจุดใกล้ที่สุด
  v_miss  numeric;   -- ระยะที่พลาดไป
  v_disc  numeric;
  v_tin   numeric;   -- ชั่วโมง จนถึงตอนแตะขอบวง
  v_close numeric;
begin
  v_re := p_row.near_east;
  v_rn := p_row.near_north;
  v_ve := p_row.east_kmh;
  v_vn := p_row.north_kmh;

  if v_re is null or v_rn is null then
    return jsonb_build_object('ok', false, 'why', 'ไม่มีฝนในวงนอก');
  end if;
  if v_ve is null or v_vn is null then
    return jsonb_build_object('ok', false, 'why', 'อ่านทิศทางไม่ได้ในรอบนี้');
  end if;

  v_dist  := sqrt(v_re * v_re + v_rn * v_rn);
  v_speed := sqrt(v_ve * v_ve + v_vn * v_vn);

  if v_dist <= v_ring then
    return jsonb_build_object('ok', true, 'inRing', true, 'etaMin', 0,
      'distKm', round(v_dist, 1),
      'why', 'ฝนอยู่ในวงแล้ว');
  end if;

  -- ก้อนฝนแทบไม่เคลื่อน ตำแหน่งวันนี้จึงบอกอะไรเรื่องพรุ่งนี้ไม่ได้
  -- ตอบว่าไม่รู้ ดีกว่าเอาความเร็วเกือบศูนย์ไปหารแล้วได้เวลาเป็นพันนาที
  if v_speed < 3 then
    return jsonb_build_object('ok', true, 'approaching', false,
      'why', 'กลุ่มฝนแทบไม่เคลื่อนที่ ' || round(v_speed, 1) || ' กม./ชม.',
      'distKm', round(v_dist, 1), 'speedKmh', round(v_speed, 1));
  end if;

  v_dot   := v_re * v_ve + v_rn * v_vn;
  v_close := -v_dot / v_dist;
  v_tcpa  := -v_dot / (v_speed * v_speed);

  -- ออกห่างตั้งแต่ตอนนี้
  if v_tcpa <= 0 then
    return jsonb_build_object('ok', true, 'approaching', false,
      'why', 'ฝนกำลังออกห่างตัวเมือง',
      'distKm', round(v_dist, 1), 'speedKmh', round(v_speed, 1),
      'closingKmh', round(v_close, 1));
  end if;

  v_miss := sqrt(power(v_re + v_ve * v_tcpa, 2) + power(v_rn + v_vn * v_tcpa, 2));

  -- วิ่งตัดหน้า เข้าใกล้แต่ไม่เข้าวง  นี่คือกรณีที่สูตรเดิมตอบผิด
  if v_miss > v_ring then
    return jsonb_build_object('ok', true, 'approaching', false,
      'why', 'ฝนวิ่งตัดหน้า ไม่เข้าวง',
      'distKm', round(v_dist, 1),
      'speedKmh', round(v_speed, 1),
      'closingKmh', round(v_close, 1),
      'missKm', round(v_miss, 1),
      'missMin', round(v_tcpa * 60),
      'ringKm', v_ring,
      'growth', p_row.spread_kmh);
  end if;

  -- เข้าวงแน่ หาเวลาที่แตะขอบวง
  v_disc := v_dot * v_dot - (v_speed * v_speed) * (v_dist * v_dist - v_ring * v_ring);
  if v_disc < 0 then
    return jsonb_build_object('ok', false, 'why', 'คำนวณจุดตัดขอบวงไม่ได้');
  end if;
  v_tin := (-v_dot - sqrt(v_disc)) / (v_speed * v_speed);
  if v_tin < 0 then v_tin := 0; end if;

  return jsonb_build_object('ok', true, 'approaching', true,
    'distKm', round(v_dist, 1),
    'speedKmh', round(v_speed, 1),
    'closingKmh', round(v_close, 1),
    'missKm', round(v_miss, 1),
    'ringKm', v_ring,
    'etaMin', round(v_tin * 60),
    'cpaMin', round(v_tcpa * 60),
    'growth', p_row.spread_kmh);
end;
$fn$;

-- ==========================================================
-- ตรวจผล  คำสั่งสุดท้ายคำสั่งเดียวที่จะแสดงผล
-- ==========================================================
-- แถวจริงสามรอบล่าสุด เทียบคำตอบเก่ากับใหม่ให้เห็นกับตา

select to_char(seen_at at time zone 'Asia/Bangkok', 'HH24:MI') as เวลา,
       round(nearest_km, 1) as ระยะกม,
       round(near_east, 1) as อยู่ตอ,
       round(near_north, 1) as อยู่เหนือ,
       round(east_kmh, 1) as วิ่งตอ,
       round(north_kmh, 1) as วิ่งเหนือ,
       coalesce(rain_eta(t.*) ->> 'why',
                'จะเข้าวงในอีก ' || (rain_eta(t.*) ->> 'etaMin') || ' นาที') as คำตอบใหม่,
       coalesce(rain_eta(t.*) ->> 'missKm', '-') as พลาดไปกม
from rain_track t
where near_east is not null
order by id desc
limit 5;
