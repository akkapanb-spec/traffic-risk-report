-- ใช้ได้เฉพาะตอนฝนวิ่งตรงเข้าหาเราเท่านั้น พอวิ่งเฉียงเมื่อไหร่ก็ตอบเกินจริง
-- และตอบเกินจริงในทางที่อันตราย คือเตือนฝนที่ไม่มีวันมา
--
-- ------------------------------------------------------------
-- สูตรที่ถูก
-- ------------------------------------------------------------
-- คิดเป็นเรื่องเรขาคณิต ไม่ใช่เรื่องระยะทางลดลง
--
--   ให้ r คือตำแหน่งของฝนเทียบกับแยกเดชาติวงศ์  หน่วยกิโลเมตร
--   ให้ v คือความเร็วของกลุ่มฝน                 หน่วยกิโลเมตรต่อชั่วโมง
--   ตำแหน่งของฝนที่เวลา t คือ  r + v*t
--
-- จุดที่เข้าใกล้ที่สุด หาได้จากเวลาที่ทำให้ระยะสั้นที่สุด
--   t ที่ใกล้ที่สุด = -(r ดอต v) หารด้วย ขนาดของ v ยกกำลังสอง
--   ระยะที่พลาดไป  = ขนาดของ (r + v*t)
--
-- ถ้าระยะที่พลาดไป มากกว่ารัศมีวง แปลว่าฝนไม่เข้าวง ไม่ต้องเตือน
-- ต่อให้ระยะห่างกำลังลดลงอยู่ก็ตาม
--
-- ถ้าระยะที่พลาดไป น้อยกว่ารัศมีวง ฝนจะเข้าวงจริง
-- เวลาที่ขอบวงถูกแตะ หาได้จากสมการกำลังสอง
--   ขนาด v ยกกำลังสอง คูณ t กำลังสอง  บวก  สองเท่าของ (r ดอต v) คูณ t
--   บวก (ขนาด r ยกกำลังสอง ลบ รัศมียกกำลังสอง)  เท่ากับศูนย์
-- เอารากที่น้อยกว่า เพราะนั่นคือตอนเข้า อีกรากคือตอนออก
--
-- ตอบเวลาที่ฝนแตะขอบวง ไม่ใช่เวลาที่ฝนถึงใจกลางเมือง
-- เพราะคนที่อยู่ริมวงเจอฝนก่อน และเป็นตัวเลขที่เอาไปใช้ได้จริงกว่า
