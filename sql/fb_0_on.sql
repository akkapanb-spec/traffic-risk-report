-- เปิดสวิตช์อย่างเดียว ไม่โพสต์อะไรออกไปในไฟล์นี้
-- ต่างจาก fb_2c_first.sql ที่เปิดสวิตช์แล้วยิงโพสต์สรุปรายสัปดาห์ทันที
--
-- หลังเปิด ระบบจะโพสต์ก็ต่อเมื่อมีตัวส่งถูกเรียก
-- ถ้ายังไม่ได้ตั้งงานตามเวลา เปิดไว้ก็ยังไม่มีอะไรเกิดขึ้น
-- ถ้าตั้งงานตามเวลาไว้แล้ว เรื่องที่ค้างอยู่จะเริ่มถูกโพสต์ในรอบถัดไป
--
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์

update bs_settings
   set val = 'true'::jsonb,
       updated_at = now()
 where key = 'fbEnabled';

-- ตรวจ  ต้องได้ true
select val as สวิตช์เฟซบุ๊ก
  from bs_settings
 where key = 'fbEnabled';

