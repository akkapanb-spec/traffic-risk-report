-- แก้ถ้อยคำบรรทัดแรกของข้อความเตือนฝน ให้ตรงกับสิ่งที่เกิดขึ้นจริง
-- ถ้ามีอักขระแปลกปลอมต่อท้ายบรรทัดสุดท้าย ให้ลบออกก่อนกด Run
-- เปลี่ยนคำเดียว  เข้า เป็น ตก  ไม่แตะบรรทัดอื่นเลย
--
-- ------------------------------------------------------------
-- ทำไมต้องแก้
-- ------------------------------------------------------------
-- บรรทัดแรกเขียนว่า ฝนกำลังเข้าเขตเมือง
-- แต่เงื่อนไขที่ทำให้ส่งคือฝนคลุมวง 8 กม. ไปแล้วอย่างน้อย 15 เปอร์เซ็นต์
--
-- 28 ส.ค. 2569 ข้อความออกเวลา 08:43 ตอนที่อ่านได้ 21.2 เปอร์เซ็นต์
-- ผู้สังเกตเจอฝนเม็ดแรกตั้งแต่ 08:23 คือก่อนหน้านั้น 20 นาที
-- ตอนที่ข้อความไปถึง ฝนตกอยู่แล้ว ไม่ได้กำลังจะเข้า
--
-- คนที่อ่านคำว่ากำลังเข้า ในขณะที่ตัวเองเปียกอยู่แล้ว จะสรุปว่าระบบช้าหรือมั่ว
-- ทั้งที่ระบบทำงานถูกต้องทุกขั้นตอน ปัญหาอยู่ที่คำ ไม่ได้อยู่ที่ระบบ
-- และความเชื่อถือเสียง่ายกว่าที่จะสร้างคืน
--
-- ข้อความยังมีประโยชน์เต็มที่แม้ฝนตกแล้ว เพราะสิ่งที่เตือนคือ
-- ไม่กี่นาทีแรกที่ผิวถนนลื่นที่สุด ซึ่งยังทันอยู่
--
-- เมื่อไรที่ทำระบบเตือนล่วงหน้าได้จริงและทดสอบผ่านแล้ว ค่อยเปลี่ยนกลับเป็นกำลังเข้า
--
-- ------------------------------------------------------------
-- ทำไมไม่พิมพ์ฟังก์ชันใหม่ทั้งตัว
-- ------------------------------------------------------------
-- rain_alert_collect ถูกต่อเติมมาหลายรอบ รอบล่าสุดคือส่วนบันทึกลง rain_track
-- ถ้าพิมพ์ใหม่จากไฟล์เก่าในรีโป ส่วนที่ต่อไว้จะหายไปโดยไม่มีข้อความเตือนใด ๆ
-- แล้วจะไม่มีใครรู้จนกว่าจะไปเปิดตารางดูแล้วพบว่าไม่มีข้อมูลใหม่เข้ามาเลย
--
-- จึงอ่านโค้ดที่ติดตั้งอยู่จริงมาแก้เฉพาะคำ แล้วติดตั้งกลับ
-- นับจุดยึดก่อนแทนที่ ถ้าไม่เจอพอดีหนึ่งแห่งให้หยุด ไม่ติดตั้งอะไรเลย

do $fn$
declare
  v_src text;
  v_a   text := 'ฝนกำลังเข้าเขตเมืองนครสวรรค์';
  v_b   text := 'ฝนกำลังตกในเขตเมืองนครสวรรค์';
  v_n   int;
begin
  select pg_get_functiondef(p.oid) into v_src
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.proname = 'rain_alert_collect';

  if v_src is null then
    raise exception 'ไม่พบ rain_alert_collect';
  end if;

  if position(v_b in v_src) > 0 then
    raise notice 'แก้ไว้แล้ว ไม่ต้องทำซ้ำ';
    return;
  end if;

  v_n := (length(v_src) - length(replace(v_src, v_a, ''))) / length(v_a);
  if v_n <> 1 then
    raise exception 'จุดยึดพบ % แห่ง ไม่ใช่ 1 แห่ง จึงไม่แก้', v_n;
  end if;

  execute replace(v_src, v_a, v_b);
  raise notice 'แก้ถ้อยคำแล้ว';
end;
$fn$;

-- ==========================================================
-- ตรวจผล  คำสั่งสุดท้ายคำสั่งเดียวที่จะแสดงผล
-- ==========================================================
-- แสดงบรรทัดแรกของข้อความ และยืนยันว่าส่วนที่ต่อไว้ก่อนหน้ายังอยู่ครบ

select 'บรรทัดแรกของข้อความตอนนี้' as รายการ,
       coalesce((select btrim(ln, ' ,''')
                 from pg_proc p join pg_namespace n on n.oid = p.pronamespace,
                      unnest(string_to_array(p.prosrc, chr(10))) as t(ln)
                 where n.nspname = 'public' and p.proname = 'rain_alert_collect'
                   and ln like '%เขตเมืองนครสวรรค์%'
                 limit 1), 'ไม่พบ') as ค่า
union all
select 'ส่วนบันทึกลง rain_track ยังอยู่ไหม',
       coalesce((select case when prosrc like '%rain_track%' then 'อยู่ครบ' else 'หายไปแล้ว ต้องแก้' end
                 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                 where n.nspname = 'public' and p.proname = 'rain_alert_collect'), 'ไม่พบ')
union all
select 'ส่วนตรวจภาพเรดาร์ค้าง ยังอยู่ไหม',
       coalesce((select case when prosrc like '%rainSameCount%' then 'อยู่ครบ' else 'หายไปแล้ว ต้องแก้' end
                 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                 where n.nspname = 'public' and p.proname = 'rain_alert_collect'), 'ไม่พบ')
union all
select 'ข้อความถัดไปจะส่งเมื่อ',
       'ฝนคลุมวง 8 กม. ตั้งแต่ ' ||
       coalesce((select val #>> array[]::text[] from bs_settings where key = 'rainMinPct'), '15') ||
       ' เปอร์เซ็นต์ขึ้นไป  และวันละหนึ่งข้อความ';
