-- เปิดสวิตช์  ตั้งแต่บรรทัดนี้เป็นต้นไป ระบบโพสต์ได้แล้ว
update bs_settings set val = 'true'::jsonb, updated_at = now() where key = 'fbEnabled';

-- ลบร่องรอยการลองเรียกตอนปิดอยู่ ถ้ามี  ไม่ใช่โพสต์จริง เป็นแค่แถวที่ค้างไว้
delete from fb_sent where kind = 'probe';

