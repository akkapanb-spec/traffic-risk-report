-- ============================================================
-- หาทุกฟังก์ชันที่มีแบ็กสแลชแปลกปลอมฝังอยู่ในโค้ด
-- ============================================================
-- ไฟล์นี้ "อ่านอย่างเดียว" ไม่สร้าง ไม่แก้ ไม่ลบ ไม่เพิ่มอะไรเลย
-- ไม่ต้องใช้ token ไม่ต้องแก้อะไรก่อนรัน มีคำสั่งเดียว
--
-- ตรวจก่อนกด Run: บรรทัดแรกของช่อง editor ต้องเป็นเส้น ==== ชุดนี้
-- ถ้ามี $0 ค้างอยู่บรรทัดสุดท้าย ให้ลบทิ้งก่อนกด Run
--
-- สาเหตุที่พบ
--   ช่องแก้ไข SQL ของ Supabase เติมแบ็กสแลชหน้าวงเล็บปีกกาปิดทุกตัว
--   เวลาลากไฟล์ไปวาง เพราะมันเข้าใจผิดว่าเป็นแม่แบบโค้ด ไม่ใช่ข้อความธรรมดา
--   ที่ผ่านมาเราเห็นมันตอนกด Run แล้วขึ้น error ก็ลบทิ้งแล้วรันใหม่
--   แต่ถ้าไฟล์ไหนรันผ่านทั้งที่มีแบ็กสแลชอยู่ข้างใน เช่นอยู่ในเครื่องหมายคำพูด
--   มันจะถูกบันทึกลงฐานข้อมูลไปด้วย และไปพังตอนฟังก์ชันทำงานจริงแทน
--
--   ตัวอย่างที่เจอ ค่าว่างของ jsonb ที่เขียนด้วยปีกกาเปิดปิดติดกัน
--   ถูกแทรกแบ็กสแลชคั่นกลาง ทำให้กลายเป็นค่าที่อ่านไม่ได้
--   ซึ่งทำให้บันทึกอุบัติเหตุไม่ได้ และแจ้งเตือนไลน์ไม่ทำงาน
--
-- ไฟล์นี้ไม่มีวงเล็บปีกกาและไม่มีแบ็กสแลชแม้แต่ตัวเดียว
-- ตรงที่ต้องค้นหาแบ็กสแลชใช้ chr(92) แทน ซึ่งคือรหัสตัวเลขของอักขระนั้น
--
-- อ่านผลยังไง
--   ทุกแถวที่ออกมา คือบรรทัดที่เสียหายและต้องซ่อม
--   ถ้าไม่มีแถวเลย แปลว่าผมเดาผิด บอกได้เลย
-- ============================================================

select p.proname as ฟังก์ชัน,
       t.ln      as บรรทัดที่,
       t.txt     as โค้ดที่เสียหาย
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
 cross join lateral unnest(string_to_array(p.prosrc, chr(10)))
       with ordinality as t(txt, ln)
 where n.nspname = 'public'
   and p.prokind = 'f'
   and position(chr(92) in t.txt) > 0
 order by p.proname, t.ln;

-- ============================================================
-- ถ่ายภาพผลลัพธ์ส่งมาครับ
-- ขอเห็นชื่อฟังก์ชันให้ครบทุกตัว จำนวนแถวรวมด้านบนก็สำคัญ
-- ผมจะได้รู้ว่าต้องซ่อมกี่จุด แล้วเขียนไฟล์ซ่อมที่ไม่มีปีกกาเลยให้
-- ============================================================
