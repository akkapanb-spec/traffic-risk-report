--
-- ------------------------------------------------------------
-- ทำไมถึงสงสัยเรื่องนี้
-- ------------------------------------------------------------
-- โพสต์ข้อความล้วนเมื่อ 28 ก.ย. เปิดออกมาเป็นโพสต์ปกติ เป็นสาธารณะ มีปุ่มโปรโมท
-- แต่ไม่อยู่บนวอลล์  และโพสต์ที่มีรูปก็ไม่อยู่เหมือนกัน
-- แปลว่าไม่เกี่ยวกับรูปเลย โพสต์จากระบบไม่ขึ้นวอลล์ทุกชนิด
--
-- เฟซบุ๊กมีสถานะหนึ่งที่อธิบายอาการนี้ได้พอดี คือ ซ่อนจากไทม์ไลน์
-- โพสต์ที่ถูกซ่อนยังมีอยู่จริง เปิดด้วยลิงก์ตรงได้ เป็นสาธารณะ และมีรหัสโพสต์
-- แต่จะไม่โผล่บนหน้าเพจ  ตรงกับทุกอย่างที่เราเห็นมา
--
-- ไฟล์นี้ถามค่า is_hidden ของโพสต์ข้อความล้วนอันนั้นโดยตรง
-- ถามอย่างเดียว ไม่เปลี่ยนอะไรทั้งสิ้น
--
-- ------------------------------------------------------------
-- ต้องแยกสองไฟล์
-- ------------------------------------------------------------
-- pg_net ยิงคำขอหลังคำสั่งจบแล้วเท่านั้น
-- รันไฟล์นี้ก่อน รอสิบวินาที แล้วรัน fb_30_read_hidden.sql

do $fn$
declare
  v_ver text;
  v_tok text;
begin
  v_ver := coalesce((select val #>> array[]::text[] from bs_settings where key = 'fbApiVersion'), 'v21.0');
  v_tok := fb_token();

  perform net.http_get(
    url := 'https://graph.facebook.com/' || v_ver ||
           '/147045742304847_1685058373190152' ||
           '?fields=id,is_hidden,is_published,is_expired,privacy,created_time,status_type,promotable_id',
    headers := jsonb_build_object('Authorization', 'Bearer ' || v_tok),
    timeout_milliseconds := 30000);

  raise notice 'ถามไปแล้ว รอสิบวินาทีแล้วรัน fb_30_read_hidden.sql';
end;
$fn$;

