select '1 ปลายทางทั้งหมดที่มี' as หมวด,
       t.target_type || ' · ' || coalesce(t.label, 'ไม่มีชื่อ') ||
       ' · รหัส ' || left(t.target_id, 12) || '...' ||
       case when t.enabled then ' · เปิด' else ' · ปิด' end as รายละเอียด
  from line_targets t

union all
select '2 ตารางบันทึกข้อความเข้า',
       case when to_regclass('public.line_hook_log') is null
            then 'ไม่มีตารางนี้ ต้องเปิดรับข้อความใหม่เพื่อให้ได้รหัสกลุ่ม'
            else 'มีตารางนี้ ให้รันคำสั่งในหมายเหตุท้ายไฟล์ต่อ' end

union all
select '3 งานตั้งเวลาที่เดินอยู่',
       j.jobname || ' · ' || j.schedule ||
       case when j.active then ' · เปิด' else ' · ปิด' end
  from cron.job j
 where j.jobname like 'line%'

order by 1, 2;

