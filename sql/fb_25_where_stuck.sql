-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- เอาทุกอย่างที่ต้องรู้มาไว้ในแถวเดียว จะได้ไม่ต้องรันหลายไฟล์
--   ขั้น            photo คือรอรหัสรูป  feed คือรอผลโพสต์  failed คือเลิกแล้ว  done คือจบ
--   ผลอัปโหลดรูป    คำตอบของจังหวะแรก  200 คือได้รหัสรูปแล้ว
--   ผลโพสต์         คำตอบของจังหวะสอง  200 คือขึ้นวอลล์แล้ว
--
-- อ่านผลอย่างไร
--   ขั้นเป็น photo และผลอัปโหลดรูปว่าง     คำตอบยังไม่มา หรือตัวสานต่อไม่ได้วิ่ง
--   ขั้นเป็น photo แต่ผลอัปโหลดรูปเป็น 200  ตัวสานต่อไม่ได้วิ่ง หรือวิ่งแล้วพัง
--   ขั้นเป็น feed และผลโพสต์ว่าง            ยิงจังหวะสองแล้ว รอคำตอบอยู่
--   ขั้นเป็น failed                         มีเหตุผลอยู่ในช่องบันทึก

select
  s.stage                                                           as ขั้น,
  s.kind || ' ' || s.ref_id                                         as เรื่อง,
  to_char(s.posted_at at time zone 'Asia/Bangkok', 'DD/MM HH24:MI') as เวลา,
  r1.status_code                                                    as ผลอัปโหลดรูป,
  left(coalesce(r1.content, r1.error_msg, ''), 150)                 as คำตอบของรูป,
  r2.status_code                                                    as ผลโพสต์,
  left(coalesce(r2.content, r2.error_msg, ''), 150)                 as คำตอบของโพสต์,
  left(coalesce(s.note, ''), 120)                                   as บันทึกของเรา
from fb_sent s
left join net._http_response r1 on r1.id = s.req_id
left join net._http_response r2 on r2.id = s.req2_id
where coalesce(s.stage, '') <> 'done'
   or s.posted_at > now() - interval '60 minutes'
order by s.posted_at desc
limit 6;

