-- ============================================================
-- ถามเฟซบุ๊กว่าโพสต์ที่สร้างไว้ มีสถานะอย่างไร  ไม่สร้างโพสต์ใหม่
-- ============================================================
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- ------------------------------------------------------------
-- อาการที่ต้องอธิบาย
-- ------------------------------------------------------------
-- รูปขึ้นในคลังรูปภาพของเพจ แต่ไม่เห็นเป็นโพสต์บนหน้าวอลล์
-- เฟซบุ๊กตอบกลับมาตอนสร้างว่ามีทั้ง id ของรูป และ post_id ของโพสต์
-- การมี post_id แปลว่ามีเรื่องราวถูกสร้างขึ้นแล้ว ไม่ได้เป็นแค่รูปในอัลบั้ม
-- จึงต้องถามกลับไปว่าเรื่องราวนั้นถูกเผยแพร่จริงไหม และใครเห็นได้บ้าง
--
-- ------------------------------------------------------------
-- ไฟล์นี้ทำอะไร
-- ------------------------------------------------------------
-- ยิงคำขอแบบอ่านอย่างเดียวไปถาม สามช่องที่ตอบคำถามนี้ได้
--   is_published   เผยแพร่แล้วหรือยัง
--   privacy        ใครเห็นได้
--   permalink_url  ที่อยู่ของโพสต์ เอาไปเปิดตรง ๆ ได้
--
-- โทเคนไม่ออกจากฐานข้อมูล ฟังก์ชัน fb_token หยิบมาใส่หัวคำขอให้เอง
-- ไม่มีการสร้าง แก้ไข หรือลบอะไรบนเพจทั้งสิ้น
--
-- ------------------------------------------------------------
-- ต้องแยกเป็นสองไฟล์
-- ------------------------------------------------------------
-- pg_net ยิงคำขอออกไปจริงหลังจากที่คำสั่งชุดนี้จบลงแล้วเท่านั้น
-- ถ้ายิงกับอ่านอยู่ไฟล์เดียวกัน จะอ่านไม่เจอคำตอบเสมอ
-- รันไฟล์นี้ก่อน รอสักสิบวินาที แล้วค่อยรัน fb_17_read_reply.sql

do $fn$
declare
  v_post text;
  v_ver  text;
  v_tok  text;
begin
  -- หา post_id จากคำตอบที่เฟซบุ๊กเคยส่งกลับมาตอนสร้างโพสต์
  select (r.content::jsonb) ->> 'post_id' into v_post
    from net._http_response r
   where r.status_code = 200
     and r.content like '%post_id%'
   order by r.id desc
   limit 1;

  if coalesce(v_post, '') = '' then
    raise notice 'ไม่พบรหัสโพสต์ในคำตอบเก่า อาจถูกล้างไปตามอายุแล้ว';
    return;
  end if;

  v_ver := coalesce((select val #>> array[]::text[] from bs_settings where key = 'fbApiVersion'), 'v21.0');
  v_tok := fb_token();

  perform net.http_get(
    url := 'https://graph.facebook.com/' || v_ver || '/' || v_post ||
           '?fields=id,created_time,is_published,privacy,permalink_url,status_type',
    headers := jsonb_build_object('Authorization', 'Bearer ' || v_tok),
    timeout_milliseconds := 30000);

  raise notice 'ถามไปแล้วเรื่องโพสต์ %  รอสิบวินาทีแล้วรัน fb_17_read_reply.sql', v_post;
end;
$fn$;

