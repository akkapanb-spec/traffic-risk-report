-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- งานชุนหงษ์ จงชิว ถูกประกาศในกลุ่มไลน์ไปแล้วด้วยมือ
-- แต่ตัวส่งอัตโนมัติของไลน์ยังไม่รู้ เพราะประกาศนี้ตั้งเวลาเริ่มไว้ 16:00
-- ตัวส่งจะเห็นมันตอน 16:00 แล้วส่งซ้ำเข้ากลุ่มเดิมอีกรอบ
--
-- สมุดกันส่งซ้ำของฝั่งไลน์คือตาราง line_adv_announced
-- จดรหัสประกาศลงไปแล้วตัวส่งจะข้าม ไม่ว่าจะเคยส่งจริงหรือไม่
-- วิธีเดียวกับที่ฝั่งเฟซบุ๊กใช้ตาราง fb_sent
--
-- ไม่กระทบฝั่งเฟซบุ๊ก คนละสมุดกัน เฟซบุ๊กยังจะประกาศงานนี้ตามปกติ

insert into line_adv_announced (adv_id, ref)
values (17, 'ประกาศในกลุ่มด้วยมือแล้ว 24 ก.ย. 2569')
on conflict (adv_id) do nothing;

-- ตรวจ  ต้องเห็นรหัส 17 อยู่ในตาราง และช่อง ไลน์จะส่งอีกไหม เป็น ไม่ส่งแล้ว
select
  t.id                                                              as รหัส,
  left(coalesce(t.title, ''), 34)                                   as เรื่อง,
  to_char(t.starts_at at time zone 'Asia/Bangkok', 'DD/MM HH24:MI') as เริ่ม,
  case when exists (select 1 from line_adv_announced n where n.adv_id = t.id)
       then 'ไม่ส่งแล้ว' else 'ยังจะส่ง' end                         as ไลน์จะส่งอีกไหม,
  case when exists (select 1 from fb_sent s
                     where s.kind = 'advisory' and s.ref_id = t.id::text)
       then 'ไม่ส่งแล้ว' else 'ยังจะส่ง' end                         as เฟซบุ๊กจะส่งไหม
from traffic_advisories t
where t.closed_at is null
  and t.ends_at >= now()
order by t.starts_at;

