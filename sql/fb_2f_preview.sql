-- ============================================================
-- โพสต์เฟซบุ๊กอัตโนมัติ  ไฟล์ 2f  ดูข้อความทั้งหมดก่อนโพสต์
-- ============================================================
-- รันได้ทุกเมื่อ ไม่ส่งอะไรออกไป
--
-- ช่องผลลัพธ์ของตัวแก้ไขตัดข้อความยาวและไม่แสดงการขึ้นบรรทัด
-- ไฟล์นี้จึงแตกข้อความเป็นบรรทัดละแถว อ่านได้ครบทุกตัวอักษร
--
-- แสดงสี่เรื่อง
--   1  สรุปรายสัปดาห์            ข้อความเดียวกับที่โพสต์ไปด้วยไฟล์ 2c
--   2  อุบัติเหตุซ้ำ              ผลล่าสุดที่คำนวณไว้
--   3  อุบัติเหตุเสียชีวิต          ตัวอย่างจากรายล่าสุดที่เสียชีวิตในที่เกิดเหตุ
--   4  เส้นทางเลี่ยง              ตัวอย่างจากประกาศล่าสุด
--
-- ข้อ 3 กับ 4 เป็นตัวอย่างจากข้อมูลเก่า ไม่ได้แปลว่าจะถูกโพสต์
-- ของเก่าทั้งหมดถูกจดว่าจัดการแล้วตอนรันไฟล์ 3a กับ 3c
-- ที่แสดงไว้เพื่อให้เห็นหน้าตาข้อความจริงเท่านั้น
--
-- ข้อ 4 ประกอบหัวและท้ายข้อความแบบเดียวกับตัวส่งใน fb_3c_advisory.sql
-- ถ้าแก้ถ้อยคำหัวท้ายที่ไฟล์นั้น ต้องแก้ที่นี่ด้วย
--
-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์

with msg as (
  select 1 as ลำดับ, 'สรุปรายสัปดาห์' as เรื่อง,
         fb_weekly_text(7) as body

  union all

  select 2, 'อุบัติเหตุซ้ำ',
         case
           when h.body is null then 'ยังไม่มีผลคำนวณ'
           when coalesce((h.body ->> 'found')::int, 0) = 0
             then 'ไม่มีจุดใดเข้าเกณฑ์ รอบนี้จะไม่โพสต์'
           else h.body ->> 'text'
         end
    from (select 1) one
    left join line_hotspot_cache h on h.id = 1

  union all

  select 3, 'อุบัติเหตุเสียชีวิต  ตัวอย่าง',
         coalesce(line_msg_death((
           select d.id from deaths d
            where btrim(coalesce(d.col_g, '')) = 'เสียชีวิตที่เกิดเหตุ'
            order by d.incident_datetime desc nulls last, d.id desc
            limit 1)), 'ไม่มีข้อมูล')

  union all

  select 4, 'เส้นทางเลี่ยง  ตัวอย่าง',
         coalesce(
           '🚧 แจ้งจุดที่ควรหลีกเลี่ยง' || chr(10) || chr(10) ||
           line_adv_item_text((select t.id from traffic_advisories t
                                order by t.created_at desc limit 1)) ||
           chr(10) || chr(10) ||
           'โปรดวางแผนการเดินทาง และใช้ความระมัดระวังเมื่อผ่านบริเวณดังกล่าว' ||
           coalesce(chr(10) || chr(10) || 'ดูรูปภาพและรายละเอียดทั้งหมด' || chr(10) ||
                    nullif((select val #>> array[]::text[] from bs_settings
                             where key = 'publicSiteUrl'), ''), '') ||
           chr(10) || chr(10) || '👮 ด้วยความปรารถนาดี น้องจราจรชอนตะวัน',
           'ไม่มีประกาศ')
)
select m.ลำดับ, m.เรื่อง, l.n as บรรทัด, l.line as ข้อความ
  from msg m
  cross join lateral string_to_table(m.body, chr(10)) with ordinality as l(line, n)
 order by m.ลำดับ, l.n;

