-- ============================================================
-- เปิดดูนโยบายความปลอดภัยระดับแถว บนตารางที่คำสั่งบันทึกเขียนลง
-- ============================================================
-- ไฟล์นี้ "อ่านอย่างเดียว" ไม่สร้าง ไม่แก้ ไม่ลบ ไม่เพิ่มอะไรเลย
-- ไม่ต้องใช้ token ไม่ต้องแก้อะไรก่อนรัน มีคำสั่งเดียว
--
-- ตรวจก่อนกด Run: บรรทัดแรกของช่อง editor ต้องเป็นเส้น ==== ชุดนี้
-- ถ้ามี $0 ค้างอยู่บรรทัดสุดท้าย ให้ลบทิ้งก่อนกด Run
--
-- ทำไมต้องดูตัวนี้
--   ตรวจมาหมดแล้วสะอาดทุกอย่าง ข้อมูลที่ส่ง เครือข่าย เบราว์เซอร์
--   ตัวตาราง โค้ดคำสั่งบันทึก ทริกเกอร์ และฟังก์ชันตรวจสิทธิ์
--
--   เหลือสิ่งเดียวที่ยังไม่เคยถูกทดสอบเลย คือนโยบายความปลอดภัยระดับแถว
--   ตอนผมลองเพิ่มแถวตรง ๆ ใน SQL Editor มันรันด้วยสิทธิ์เจ้าของฐานข้อมูล
--   ซึ่งข้ามนโยบายพวกนี้ไปทั้งหมด จึงไม่เคยพิสูจน์อะไรเลย
--
--   นโยบายพวกนี้ทำงานตอนเพิ่มหรือแก้ข้อมูลจริงเท่านั้น
--   ตรงกับอาการที่เจอพอดี คือพังเฉพาะตอนมีสิทธิ์จริงและเพิ่มข้อมูลจริง
--
-- อ่านผลยังไง
--   ดูคอลัมน์ เงื่อนไข กับ เงื่อนไขตอนเพิ่ม
--   ถ้าบรรทัดไหนมีคำว่า json อยู่ในเงื่อนไข นั่นคือตัวการ
-- ============================================================

select 'นโยบาย' as หมวด,
       pol.tablename  as ตาราง,
       pol.policyname as ชื่อนโยบาย,
       pol.cmd        as ใช้กับคำสั่ง,
       coalesce(pol.qual, 'ไม่มี')       as เงื่อนไข,
       coalesce(pol.with_check, 'ไม่มี') as เงื่อนไขตอนเพิ่ม
  from pg_policies pol
 where pol.schemaname = 'public'
   and pol.tablename in ('accidents', 'deaths', 'injuries', 'officer_sessions', 'officers')

union all

select 'เจ้าของคำสั่งบันทึก',
       'officer_save_accident',
       pg_get_userbyid(p.proowner),
       case when p.prosecdef then 'security definer' else 'security invoker' end,
       'ถ้าเจ้าของไม่ใช่ผู้ดูแลระบบ นโยบายจะยังทำงานอยู่',
       'ไม่มี'
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
 where n.nspname = 'public' and p.proname = 'officer_save_accident'

order by 1, 2, 3;

