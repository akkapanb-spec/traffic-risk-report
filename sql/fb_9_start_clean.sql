-- ==========================================================
-- 1  จดเฉพาะประกาศที่ถึงเวลาเริ่มไปแล้ว
-- ==========================================================

insert into fb_sent(kind, ref_id, ok, note)
select 'advisory', id::text, true, 'ข้ามตอนเปิดใช้งาน เพราะเริ่มไปก่อนที่เฟซบุ๊กจะเปิด'
  from traffic_advisories
 where starts_at <= now()
on conflict (kind, ref_id) do nothing;

-- ==========================================================
-- 2  ตรวจ  ดูว่าอะไรถูกข้าม และอะไรยังรอขึ้นเพจอยู่
-- ==========================================================
-- ช่อง สถานะ ต้องอ่านได้ว่า งานชุนหงษ์ยังเป็น รอขึ้นเพจเมื่อถึงเวลา
-- ถ้าขึ้นว่า ข้ามแล้ว แปลว่าผิด อย่าเพิ่งเปิดสวิตช์ ให้บอกก่อน

select
  t.id                                                      as รหัส,
  left(coalesce(t.title, ''), 34)                           as เรื่อง,
  to_char(t.starts_at at time zone 'Asia/Bangkok', 'DD/MM HH24:MI') as เริ่ม,
  to_char(t.ends_at   at time zone 'Asia/Bangkok', 'DD/MM HH24:MI') as สิ้นสุด,
  case
    when exists (select 1 from fb_sent s
                  where s.kind = 'advisory' and s.ref_id = t.id::text)
      then 'ข้ามแล้ว ไม่ขึ้นเพจ'
    when t.closed_at is not null then 'ปิดไปแล้ว'
    when t.starts_at > now()     then 'รอขึ้นเพจเมื่อถึงเวลา'
    when t.ends_at   < now()     then 'หมดเวลาแล้ว'
    else 'จะขึ้นเพจในรอบถัดไป'
  end                                                       as สถานะ
from traffic_advisories t
where t.ends_at >= now() - interval '1 day'
order by t.starts_at desc;

