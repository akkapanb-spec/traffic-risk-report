--
-- ------------------------------------------------------------
-- ทำไมต้องจดของที่ยังไม่หมดอายุด้วย
-- ------------------------------------------------------------
-- ประกาศที่ยังมีผลอยู่คือของจริงที่ประชาชนควรรู้ ปกติควรได้ขึ้นเพจ
-- แต่คราวนี้ตั้งใจข้าม เพราะโพสต์แรกของเพจคือหน้าตาของระบบทั้งระบบ
-- งานซ่อมท่อประปาที่จะหมดอายุตอนหกโมงเย็นวันนี้ ไม่ใช่โพสต์เปิดตัวที่ดี
-- ของพวกนี้ยังดูได้บนหน้าเว็บสาธารณะตามปกติ ไม่ได้หายไปไหน
--
-- ไม่ต้องจดฝั่งข่าวเสียชีวิต เพราะรายล่าสุดในระบบคือ 19 ส.ค.
-- ซึ่งพ้นกรอบ 48 ชั่วโมงที่ตัวส่งมองย้อนหลังไปนานแล้ว
-- และไม่ต้องจดฝั่งจุดเสี่ยงซ้ำกับสรุปรายสัปดาห์ เพราะทั้งคู่รอถึงวันจันทร์

-- ==========================================================
-- 1  จดประกาศทั้งหมดที่มีอยู่ตอนนี้
-- ==========================================================

insert into fb_sent(kind, ref_id, ok, note)
select 'advisory', id::text, true, 'ข้ามตอนเปิดใช้งาน เพื่อให้โพสต์แรกของเพจเป็นสรุปรายสัปดาห์'
  from traffic_advisories
on conflict (kind, ref_id) do nothing;

-- ==========================================================
-- 2  ตรวจ  ต้องไม่เหลือประกาศที่รอโพสต์เลยสักรายการ
-- ==========================================================
-- ช่อง รอโพสต์อยู่ ต้องเป็น 0  ถ้าไม่ใช่ อย่าเพิ่งเปิดสวิตช์

select
  (select count(*) from traffic_advisories)                   as ประกาศทั้งหมด,
  (select count(*) from fb_sent where kind = 'advisory')      as จดไว้แล้ว,
  (select count(*) from traffic_advisories t
     where t.closed_at is null
       and t.starts_at <= now()
       and t.ends_at   >= now()
       and not exists (select 1 from fb_sent s
                        where s.kind = 'advisory' and s.ref_id = t.id::text)) as รอโพสต์อยู่,
  (select count(*) from deaths d
     where d.incident_datetime >= now() - interval '48 hours'
       and not exists (select 1 from fb_sent s
                        where s.kind = 'death' and s.ref_id = d.id::text))    as ข่าวเสียชีวิตที่รออยู่,
  (select val #>> array[]::text[] from bs_settings where key = 'fbEnabled')   as สวิตช์เฟซบุ๊ก;

