-- ใช้ตอบคำถามว่าโพสต์ถูกสร้างจริงไหม ไม่ได้ตอบว่ามีคนเห็นกี่คน
-- จำนวนคนเห็นต้องดูที่ Business Suite ช่องการเข้าถึง
--
-- ขั้นแต่ละแบบ
--   photo    อัปโหลดรูปแล้ว รอรหัสรูป
--   feed     สร้างโพสต์บนวอลล์แล้ว รอรหัสโพสต์
--   comment  โพสต์ขึ้นแล้ว กำลังใส่ลิงก์ในคอมเมนต์
--   done     จบแล้ว ดูเหตุผลในช่องบันทึก
--   failed   เลิกกลางทาง มีเหตุผลในช่องบันทึก
--
-- ช่องผลที่เป็นค่าว่างไม่ได้แปลว่าล้มเหลว
-- คำตอบของ pg_net มีอายุประมาณหกชั่วโมงแล้วถูกล้างทิ้ง
-- ถ้ามีรหัสโพสต์อยู่ แปลว่าเฟซบุ๊กสร้างโพสต์ให้แล้วจริง ไม่ว่าช่องผลจะว่างหรือไม่

select
  s.stage                                                           as ขั้น,
  s.kind || ' ' || s.ref_id                                         as เรื่อง,
  to_char(s.posted_at at time zone 'Asia/Bangkok', 'DD/MM HH24:MI') as เวลา,
  s.photo_id                                                        as รหัสรูป,
  s.post_id                                                         as รหัสโพสต์,
  r1.status_code                                                    as ผลรูป,
  r2.status_code                                                    as ผลโพสต์,
  r3.status_code                                                    as ผลคอมเมนต์,
  left(coalesce(s.note, ''), 110)                                   as บันทึกของเรา
from fb_sent s
left join net._http_response r1 on r1.id = s.req_id
left join net._http_response r2 on r2.id = s.req2_id
left join net._http_response r3 on r3.id = s.req3_id
where s.posted_at > now() - interval '7 days'
order by s.posted_at desc
limit 12;

