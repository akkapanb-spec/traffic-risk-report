-- ห้ามมีปีกกาในไฟล์นี้ ตัวแก้ไขจะเติมแบ็กสแลชให้
-- ก่อนกด Run ให้ลบสิ่งที่ตัวแก้ไขเติมไว้ท้ายสุดออกก่อน เป็นดอลลาร์ตามด้วยเลขศูนย์
--
-- ------------------------------------------------------------
-- ทำไมไฟล์ก่อนหน้าไม่แสดงอะไร
-- ------------------------------------------------------------
-- ตัวสานต่อตอบว่าไม่มีงานค้างเลยสักชิ้น ทั้งสร้างโพสต์ ปิดงาน และไม่สำเร็จ เป็นศูนย์หมด
-- แปลว่าไม่มีแถวไหนค้างอยู่ขั้น photo หรือ feed  ทุกแถวจบไปแล้ว
--
-- แล้วตารางที่ต่อท้ายก็ว่าง เพราะผมกรองไว้แค่สองชั่วโมงหลังสุด
-- ของที่จบไปแล้วและเก่ากว่านั้นจึงหลุดออกจากตารางไปทั้งหมด เป็นความผิดพลาดของผมเอง
--
-- ไฟล์นี้เปิดกว้างเป็นเจ็ดวันและไม่กรองขั้นเลย
--
-- ------------------------------------------------------------
-- สิ่งที่ต้องดู
-- ------------------------------------------------------------
-- รหัสโพสต์     ถ้ามีค่า แปลว่าเฟซบุ๊กสร้างโพสต์ให้แล้วจริง
-- คำตอบของโพสต์ คำตอบจริงของจังหวะสอง บอกว่าสำเร็จหรือถูกปฏิเสธเพราะอะไร
-- บันทึกของเรา  ขึ้นวอลล์แล้ว คือเดินครบเส้นทาง

select
  s.stage                                                           as ขั้น,
  s.kind || ' ' || s.ref_id                                         as เรื่อง,
  to_char(s.posted_at at time zone 'Asia/Bangkok', 'DD/MM HH24:MI') as เวลา,
  s.photo_id                                                        as รหัสรูป,
  s.post_id                                                         as รหัสโพสต์,
  r1.status_code                                                    as ผลรูป,
  r2.status_code                                                    as ผลโพสต์,
  left(coalesce(r2.content, r2.error_msg, ''), 150)                 as คำตอบของโพสต์,
  left(coalesce(s.note, ''), 100)                                   as บันทึกของเรา
from fb_sent s
left join net._http_response r1 on r1.id = s.req_id
left join net._http_response r2 on r2.id = s.req2_id
where s.posted_at > now() - interval '7 days'
order by s.posted_at desc
limit 12;

