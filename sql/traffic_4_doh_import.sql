set search_path = public, extensions;

create table if not exists tv_ref_volume (
  id          bigserial primary key,
  dept        text not null,              -- กรมทางหลวง หรือ กรมทางหลวงชนบท
  road_code   text not null,              -- ทล.1 / นว.1111
  section     text,                       -- ตอนควบคุม เฉพาะของกรมทางหลวง
  road_name   text not null,
  km_point    text,                       -- จุดสำรวจ เช่น 331+276
  year        int  not null,
  mc          int,                        -- จักรยานยนต์ คัน/วัน
