-- ============================================================
-- อ่านรายการอ้างอิงทั้งสองกรม
-- ============================================================
create or replace function tv_ref_list(p_token text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err jsonb;
begin
  v_err := admin_check_(p_token);
  if v_err is not null then return v_err; end if;

  return jsonb_build_object('success', true,
    'rows', coalesce((select jsonb_agg(jsonb_build_object(
        'id', v.id, 'dept', v.dept, 'road_code', v.road_code, 'section', v.section,
        'road_name', v.road_name, 'km_point', v.km_point, 'year', v.year,
        'mc', v.mc, 'sum_aadt', v.sum_aadt, 'office', v.office,
        -- ถ้ามีถนนในโครงข่ายที่รหัสตรงกัน บอกไว้ให้กดใช้ได้เลย
        'road_id', (select r.id from rn_roads r
                    where rn_road_norm(r.code) = rn_road_norm(v.road_code) limit 1))
      order by v.sum_aadt desc)
      from tv_ref_volume v), '[]'::jsonb));
end $$;

-- ============================================================
-- เอาค่าอ้างอิงไปใช้กับถนนในโครงข่าย
-- ============================================================
-- ไม่ทำอัตโนมัติ เพราะตอนควบคุมของกรมทางหลวงยาวกว่าถนนที่เราวาดมาก
-- ทล.1 สายเดียวมีหลายจุดสำรวจ ค่าต่างกันเกินเท่าตัว ต้องให้คนเลือกจุดที่ตรงกับพื้นที่จริง
create or replace function tv_use_ref(p_token text, p_ref_id bigint, p_road_id bigint)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err jsonb; v tv_ref_volume%rowtype;
begin
  v_err := admin_check_(p_token);
  if v_err is not null then return v_err; end if;

  select * into v from tv_ref_volume where id = p_ref_id;
  if not found then return jsonb_build_object('success', false, 'message', 'ไม่พบรายการอ้างอิงนี้'); end if;
  if not exists (select 1 from rn_roads where id = p_road_id) then
    return jsonb_build_object('success', false, 'message', 'ไม่พบถนนสายนี้ในโครงข่าย');
  end if;

  insert into rn_traffic_volume (road_id, year, aadt, source, note)
  values (p_road_id, v.year, v.sum_aadt, v.source,
          'นำมาจาก ' || v.road_code || coalesce(' ตอน ' || v.section, '') ||
          coalesce(' กม.' || v.km_point, '') || ' — ' || v.road_name)
  on conflict (road_id, year, km_from, km_to) do update set
    aadt = excluded.aadt, source = excluded.source, note = excluded.note, updated_at = now();

  return jsonb_build_object('success', true,
    'message', 'ใช้ค่า ' || v.sum_aadt || ' คัน/วัน จาก ' || v.road_code || ' แล้ว');
end $$;

grant execute on function tv_ref_list(text)                 to anon, authenticated;
grant execute on function tv_use_ref(text, bigint, bigint)  to anon, authenticated;

