-- ตรวจเรดาร์ถี่ขึ้นเป็นทุก 7 นาที
-- ถ้ามีอักขระแปลกปลอมต่อท้ายบรรทัดสุดท้าย ให้ลบออกก่อนกด Run
--
-- ------------------------------------------------------------
-- ทำไมต้องถี่ขึ้น
-- ------------------------------------------------------------
-- 27 ส.ค. 2569 เวลา 19:30 เรดาร์อ่านได้ 2 เปอร์เซ็นต์ ยังไม่ถึงเกณฑ์
--              เวลา 19:45 อ่านได้ 17.9 เปอร์เซ็นต์ เกินเกณฑ์แล้ว
-- ฝนเข้ามาระหว่างสองรอบนั้น ประชาชนจึงรู้ช้ากว่าที่ควรถึง 15 นาที
-- ซึ่งเป็นเวลาที่คนขี่มอเตอร์ไซค์ออกจากบ้านไปแล้ว
--
-- ที่ 7 นาที ช่องว่างเหลือครึ่งเดียว และรวมเวลารออ่านผลอีก 1 นาที
-- กรณีแย่ที่สุดคือรู้ช้า 8 นาที จากเดิม 20 นาที
--
-- ------------------------------------------------------------
-- ทำไมไม่ถี่กว่านี้
-- ------------------------------------------------------------
-- ตรวจถี่กว่าที่เรดาร์ออกภาพใหม่ ไม่ได้ข้อมูลเพิ่ม ได้แต่ภาพเดิมซ้ำ
-- วัดจริงจากลายนิ้วมือภาพ 20 รอบล่าสุด ทุกรอบได้ภาพใหม่ไม่ซ้ำเลย
-- แปลว่าเรดาร์ออกภาพถี่กว่า 15 นาที แต่ยังไม่รู้ว่าถี่แค่ไหน
-- 7 นาทีจึงเป็นการเข้าใกล้โดยไม่เสี่ยงดึงภาพซ้ำจนเปลืองเครื่องของกรมฯ ฟรี ๆ
--
-- ภาพหนึ่งใบหนัก 660 กิโลไบต์ ที่ 7 นาทีเท่ากับวันละ 216 ครั้ง ราว 140 เมกะไบต์
-- เดิม 15 นาทีคือวันละ 96 ครั้ง ราว 63 เมกะไบต์
-- เป็นภาระที่เพิ่มขึ้นบนเครื่องของราชการ จึงต้องแก้หนังสือขออนุญาตให้ตรงด้วย
--
-- ------------------------------------------------------------
-- ระยะห่างระหว่างยิงกับอ่าน ลดจาก 5 นาทีเหลือ 1 นาที
-- ------------------------------------------------------------
-- 5 นาทีเผื่อไว้มากเกินจำเป็น ตัวอ่านเรดาร์ใช้เวลาจริงราว 1 ถึง 3 วินาที
-- และตั้งเวลารอไว้ 20 วินาทีอยู่แล้ว 1 นาทีจึงเหลือเฟือ
-- ถ้าเผลอตั้งให้อ่านเร็วกว่าที่คำตอบมาถึง จะได้ผลว่ายังไม่มีคำตอบให้อ่าน
-- ซึ่งไม่เสียหาย แค่เสียรอบ แต่ไม่ควรปล่อยให้เกิดบ่อย

select cron.unschedule(jobname) from cron.job where jobname in ('rain-fire', 'rain-collect');

-- ยิงถามที่นาที 0 7 14 21 28 35 42 49 56 ของทุกชั่วโมง
select cron.schedule('rain-fire',    '0,7,14,21,28,35,42,49,56 * * * *', 'select rain_alert_fire()');

-- อ่านผลถัดจากนั้นหนึ่งนาที
select cron.schedule('rain-collect', '1,8,15,22,29,36,43,50,57 * * * *', 'select rain_alert_collect()');

-- ==========================================================
-- ตรวจผล  คำสั่งสุดท้ายคำสั่งเดียวที่จะแสดงผล
-- ==========================================================

select 'งานตั้งเวลาใหม่' as รายการ,
       coalesce((select string_agg(jobname || ' = ' || schedule, chr(10) order by jobname)
                 from cron.job where jobname like 'rain-%'), 'ไม่พบ') as ค่า
union all
select 'ตรวจกี่ครั้งต่อวัน', '216 ครั้ง  จากเดิม 96 ครั้ง'
union all
select 'กรณีแย่ที่สุดรู้ช้ากี่นาที', '8 นาที  จากเดิม 20 นาที'
union all
select 'ความถี่ส่งข้อความ', 'ยังวันละไม่เกินหนึ่งข้อความเหมือนเดิม ไม่เปลี่ยน'
union all
select 'ต้องแก้ตามด้วย', 'หนังสือขออนุญาตกรมฝนหลวง ระบุไว้ว่าทุก 15 นาที ต้องแก้เป็น 7 นาที';
